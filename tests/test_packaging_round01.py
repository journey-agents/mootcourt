"""T-076 (registered as T-078; round 01 R4, the reproducibility chair): packaging.

The table headers name their source relative to the run folder and never an absolute data-root path; ``make tables`` rebuilds them from the
run folder and ``make paper`` depends on it; the sdist carries the package, its examples and its tests and not the paper's run folders;
the continuous-integration job and the Makefile pass ``-q`` once, so the pytest count line is in the log.
"""
from __future__ import annotations

import importlib.util
import json
import re
import shutil
import subprocess
import tarfile
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]


def _tables():
    spec = importlib.util.spec_from_file_location("build_tables_pkg", ROOT / "paper" / "build_tables.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def test_a_table_header_names_its_source_relative_to_the_run_folder_and_never_the_absolute_path(tmp_path):
    bt = _tables()
    run = tmp_path / "run-folder"
    (run / "ablations").mkdir(parents=True)
    diag = {"rows": [{"n_tests": 120, "rows_per_cell": 80.0, "cells": 6, "mean_gain": 0.001, "mean_gain_se": 0.002, "ratio_of_means": 0.5,
                      "share_gain_positive": 0.5, "share_admitted": 0.1}], "multiplier": 2.0}
    (run / "paper-extras-synthetic-SID.json").write_text(json.dumps({"guard_gain_diagnostic": diag}))
    out = tmp_path / "tables"
    out.mkdir()
    bt.set_reports_root(str(run))
    bt.guard_gain_table(str(run), str(out))
    header = (out / "guard-gain-diagnostic.tex").read_text(encoding="utf-8").splitlines()[0]
    assert header.startswith("% generated by paper/build_tables.py from paper-extras-synthetic-SID.json"), header
    assert str(run) not in header and str(tmp_path) not in header
    # the same with a relative run folder given with a trailing slash, as make passes it
    rel = Path("paper") / "data" / "run5-period-rule"
    assert bt.relative_to_run(f"{rel}/backtest-upworthy-S.json; {rel}/ablations/backtest-upworthy-S--x.json", str(rel) + "/") == (
        "backtest-upworthy-S.json; ablations/backtest-upworthy-S--x.json"
    )


def test_the_committed_tables_name_no_absolute_data_root_path():
    bad = []
    for f in sorted((ROOT / "paper" / "tables").glob("*.tex")):
        head = f.read_text(encoding="utf-8").splitlines()[0]
        if head.startswith("% generated by") and re.search(r"from (/|~|[A-Za-z]:\\)", head):
            bad.append(f.name)
    assert not bad, bad


def test_the_makefile_has_a_tables_target_that_make_paper_depends_on_and_needs_no_data_root():
    mk = (ROOT / "Makefile").read_text(encoding="utf-8")
    assert re.search(r"^tables:\s*$", mk, re.M) and "build_tables.py --reports $(RUN) --out paper/tables" in mk
    paper_rule = re.search(r"^paper:\s*(.*)$", mk, re.M).group(1).split()
    assert "tables" in paper_rule and "paper-figures" in paper_rule
    block = mk[mk.index("\ntables:"):].split("\n\n", 1)[0]
    assert "$(STORE)" not in block and "$(REPORTS)" not in block and "MOOTCOURT_DATA_ROOT" not in block


@pytest.mark.skipif(shutil.which("uv") is None, reason="uv is not on the path")
def test_the_sdist_holds_the_package_its_examples_and_its_tests_and_not_the_paper_runs(tmp_path):
    subprocess.run(["uv", "build", "--sdist", "--out-dir", str(tmp_path)], cwd=ROOT, check=True, capture_output=True, text=True)
    archive = next(tmp_path.glob("mootcourt-*.tar.gz"))
    with tarfile.open(archive) as tar:
        names = ["/".join(n.split("/")[1:]) for n in tar.getnames() if "/" in n]
    tops = {n.split("/")[0] for n in names}
    assert {"src", "tests", "examples", "pyproject.toml", "README.md", "PKG-INFO"} <= tops, tops
    assert not tops & {"paper", "docs", "scripts", "reports", "data", "models", "cards", ".github", "uv.lock", "site", "dist"}, tops
    assert any(n.startswith("src/mootcourt/cli.py") for n in names) and any(n.startswith("tests/test_card.py") for n in names)
    assert archive.stat().st_size < 2_000_000


def test_ci_and_the_makefile_pass_q_once_so_the_count_line_is_printed():
    assert '-q' in (ROOT / "pyproject.toml").read_text(encoding="utf-8").split("[tool.pytest.ini_options]", 1)[1].split("\n\n")[0]
    ci = (ROOT / ".github" / "workflows" / "ci.yml").read_text(encoding="utf-8")
    runs = [line for line in ci.splitlines() if "pytest" in line]
    assert runs and all(" -q" not in line and " -qq" not in line for line in runs), runs
    mk = [line for line in (ROOT / "Makefile").read_text(encoding="utf-8").splitlines() if "pytest" in line]
    assert mk and all(" -q" not in line for line in mk), mk
