"""Draw the paper's figures from Moot Court report JSON files.

Usage: python scripts/paper_figures.py [--run paper/data/run8-randomization-window] [--out paper/figures]
                                       [--cautionary paper/data/run1-relative-lift]

One vector PDF per figure (and per archive where the data is per archive), written next to ``figures.json``, which lists every file
with the JSON it was drawn from and every plotted value as (table path, row selector, field, value) so each number in a figure traces
to one JSON path, the way ``paper/build_tables.py`` traces the tables. Output is deterministic: Agg backend, TrueType fonts embedded
as Type 42, no creation date, a fixed producer string, and every iteration order sorted.
"""

