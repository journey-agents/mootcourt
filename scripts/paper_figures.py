def fig_learning(figs, lc, source, used):
    rows = lc["rows"]
    rungs = [r for r in ("P1", "P2", "local_eb", "GBM", "text_lr") if any(x["rung"] == r for x in rows)]
    fig, ax = plt.subplots(figsize=(COL_W, 2.2))
    ax.axhline(0, color=GREY, lw=0.8, ls="--", zorder=1)
    centre = []
    for rg in rungs:
        fr = sorted(x["fraction"] for x in rows if x["rung"] == rg and x.get("skill") is not None)
        sk, lo, hi = [], [], []
        for f in fr:
            w = {"rung": rg, "fraction": f}
            sk.append(used.get(lc, "rows", w, "skill"))
            lo.append(used.get(lc, "rows", w, "skill_lo"))
            hi.append(used.get(lc, "rows", w, "skill_hi"))
        centre += sk
        ax.fill_between(fr, lo, hi, color=COLOUR[rg], alpha=0.10, lw=0, zorder=2)
        ax.plot(fr, sk, color=COLOUR[rg], marker=MARKER[rg], label=rg, zorder=3)
    ax.set_xscale("log")
    fracs = sorted(lc["fractions"])
    ax.set_xticks(fracs)
    ax.set_xticklabels([f"{f * 100:g}" for f in fracs])
    ax.minorticks_off()
    span = max(centre) - min(centre)
    ax.set_ylim(min(centre) - 0.15 * span - 0.02, max(centre) + 0.15 * span + 0.02)
    ax.set_xlabel("Training data, percent of the available rows")
    ax.set_ylabel("Brier skill against P0")
    ax.legend(frameon=False, ncol=5, loc="upper center", bbox_to_anchor=(0.5, -0.2), handlelength=1.2, columnspacing=0.8)
    style_axes(ax)
    fig.tight_layout(pad=0.4)
    figs.save(fig, f"learning-curve-{source}.pdf", used,
              "line is the mean over seeds, band is skill_lo to skill_hi (percentile bootstrap of the seed mean); bands are clipped at the axis")


