def load(path):
    with open(path) as fh:
        return json.load(fh)


def rel(path):
    """Path as recorded: relative to the project root when inside it, as given otherwise."""
    ap = os.path.abspath(path)
    return os.path.relpath(ap, ROOT) if ap.startswith(ROOT + os.sep) else path


def find(folder, pattern):
    hits = sorted(glob.glob(os.path.join(folder, pattern)))
    return hits[0] if hits else None


class Used:
    """Record of every JSON value a figure plots: path of the table (dotted), row selector, field, value."""

    def __init__(self, jpath):
        self.jpath, self.items, self.derived, self.cur = jpath, [], [], None

    def get(self, doc, table, where, field):
        node = doc
        for part in table.split("."):
            node = node[part]
        hits = [r for r in node if all(r.get(k) == v for k, v in where.items())]
        if len(hits) != 1:
            raise ValueError(f"{self.jpath} {table} {where}: expected one row, found {len(hits)}")
        value = hits[0].get(field)
        if value is None:
            return None
        item = {"table": table, "where": dict(where), "field": field, "value": value}
        if self.cur:
            item["json"] = self.cur
        self.items.append(item)
        return value

    def keys(self):
        return sorted({f"{i['table']}.{i['field']}" for i in self.items})


class Figures:
    def __init__(self, out):
        self.out, self.entries, self.skipped = out, [], []
        os.makedirs(out, exist_ok=True)

    def save(self, fig, name, used, note):
        path = os.path.join(self.out, name)
        meta = {
            "CreationDate": None, "Creator": "scripts/paper_figures.py", "Producer": "matplotlib",
            "Subject": f"generated by scripts/paper_figures.py from {used.jpath}", "Keywords": "src: " + "; ".join(used.keys()),
        }
        fig.savefig(path, format="pdf", metadata=meta)
        plt.close(fig)
        self.entries.append({"file": name, "json": used.jpath, "keys": used.keys(), "note": note, "values": used.items, "derived": used.derived})
        print("wrote", path)

    def skip(self, name, why):
        self.skipped.append({"file": name, "reason": why})
        print("skipped", name, "-", why)

    def write_index(self, run, cautionary):
        doc = {"generated_by": "scripts/paper_figures.py", "run_folder": rel(run), "cautionary_folder": rel(cautionary),
               "figures": sorted(self.entries, key=lambda e: e["file"]), "skipped": sorted(self.skipped, key=lambda e: e["file"])}
        path = os.path.join(self.out, "figures.json")
        with open(path, "w") as fh:
            json.dump(doc, fh, indent=1, sort_keys=True)
            fh.write("\n")
        print("wrote", path)


def style_axes(ax):
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)


def rungs_present(rows, wanted):
    have = {r["rung"] for r in rows}
    return [r for r in wanted if r in have]


