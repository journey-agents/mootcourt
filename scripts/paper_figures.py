def fig_reliability(figs, doc, source, used, level=0.90):
    t = doc["tables"]["reliability_bins"]
    rungs = rungs_present(t, LADDER)
    widths = {round(r["hi"] - r["lo"], 6) for r in t}
    fig, axes = plt.subplots(1, len(rungs), figsize=(WIDE_W, 2.3), squeeze=False)
    axes = axes[0]
    alpha_tail = (1 - level) / 2
    lim = 0.0
    drawn = {}
    for rg in rungs:
        pts = []
        for r in sorted((r for r in t if r["rung"] == rg and r["n"] > 0), key=lambda r: r["bin"]):
            w = {"rung": rg, "bin": r["bin"]}
            n = used.get(doc, "tables.reliability_bins", w, "n")
            p = used.get(doc, "tables.reliability_bins", w, "mean_p")
            f = used.get(doc, "tables.reliability_bins", w, "freq")
            lo = float(binom.ppf(alpha_tail, n, p)) / n
            hi = float(binom.ppf(1 - alpha_tail, n, p)) / n
            used.derived.append({"rung": rg, "bin": r["bin"], "what": f"central {int(level * 100)} percent interval of Binomial(n, mean_p) over n",
                                 "lo": lo, "hi": hi, "from": ["n", "mean_p"]})
            pts.append((p, f, lo, hi, n))
        drawn[rg] = pts
        lim = max([lim] + [max(p, f, hi) for p, f, _, hi, _ in pts])
    lim = min(1.0, round(lim * 1.12 + 0.01, 2))
    for ax, rg in zip(axes, rungs):
        ax.plot([0, lim], [0, lim], color=GREY, lw=0.8, ls="--", zorder=1)
        pts = drawn[rg]
        for p, _f, lo, hi, _n in pts:
            ax.vlines(p, lo, hi, color=COLOUR[rg], alpha=0.35, lw=3.0, zorder=2)
        ax.plot([p[0] for p in pts], [p[1] for p in pts], color=COLOUR[rg], marker=MARKER[rg], zorder=3, lw=0.7)
        ax.set_xlim(0, lim)
        ax.set_ylim(0, lim)
        ax.set_aspect("equal", adjustable="box")
        ax.set_xlabel(f"Mean predicted probability, {rg}")
        ax.set_ylabel("Observed frequency")
        style_axes(ax)
    fig.tight_layout(pad=0.4, w_pad=0.8)
    figs.save(fig, f"reliability-{source}.pdf", used,
              f"bins are equal width ({sorted(widths)}), empty bins dropped; wide light bars are the central {int(level * 100)} percent interval "
              "of the observed frequency under perfect calibration, from Binomial(n, mean_p), which treats rows as independent")


