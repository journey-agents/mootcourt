def fig_cautionary(figs, run1_path, run3_path, source="upworthy"):
    d1, d3 = load(run1_path), load(run3_path)
    name = f"cautionary-{source}.pdf"
    p1 = [r for r in d1["tables"]["aggregate"] if r["rung"] == "P1" and r.get("brier_skill") is not None]
    if not p1:
        figs.skip(name, f"{rel(run1_path)} has no P1 brier_skill rows in tables.aggregate")
        return
    used = Used(f"{rel(run1_path)} and {rel(run3_path)}")
    cells = ["ALL", "headline_only", "image_only", "both"]
    cells = [c for c in cells if any(r["cell"] == c for r in p1) and any(r["cell"] == c and r["rung"] == "P1" for r in d3["tables"]["aggregate"])]
    fig, axes = plt.subplots(1, 2, figsize=(COL_W, 1.9), sharey=True)
    for ax, doc, label, path in ((axes[0], d1, "Run 1: relative lift", run1_path), (axes[1], d3, "Run 3: pre-launch clean", run3_path)):
        used.cur = rel(path)
        ax.axhline(0, color=GREY, lw=0.8, ls="--", zorder=1)
        for i, c in enumerate(cells):
            w = {"cell": c, "rung": "P1"}
            y = used.get(doc, "tables.aggregate", w, "brier_skill")
            lo = used.get(doc, "tables.aggregate", w, "brier_skill_lo")
            hi = used.get(doc, "tables.aggregate", w, "brier_skill_hi")
            ax.errorbar([i], [y], yerr=[[y - lo], [hi - y]], color=COLOUR["P1"], marker=MARKER["P1"], ms=3.5, capsize=1.5,
                        capthick=0.6, lw=0.8, ls="none")
        ax.set_xticks(range(len(cells)))
        ax.set_xticklabels([c.replace("_", " ") for c in cells], rotation=30, ha="right")
        ax.set_xlim(-0.5, len(cells) - 0.5)
        ax.set_xlabel(label)
        style_axes(ax)
    axes[0].set_ylabel("P1 Brier skill, 90 percent interval")
    fig.tight_layout(pad=0.4, w_pad=0.6)
    figs.save(fig, name, used, "same quantity (P1 Brier skill by cell) in the relative-lift run and the pre-launch-clean run")


def build(run, out, cautionary):
    figs = Figures(out)
    plt.rcParams.update(RC)
    for source in SOURCES:
        jp = find(run, f"backtest-{source}-*.json")
        if jp is None:
            figs.skip(f"*-{source}.pdf", f"no backtest-{source}-*.json in {rel(run)}")
            continue
        doc = load(jp)
        for fn, fname in ((fig_coverage_se, "coverage-se"), (fig_coverage_exposure, "coverage-exposure"), (fig_decision, "decision-value"),
                          (fig_reliability, "reliability")):
            try:
                fn(figs, doc, source, Used(rel(jp)))
            except KeyError as exc:
                figs.skip(f"{fname}-{source}.pdf", f"{rel(jp)} lacks {exc}")
        lp = find(run, f"learning-curve-{source}-*.json")
        if lp is None:
            figs.skip(f"learning-curve-{source}.pdf", f"no learning-curve-{source}-*.json in {rel(run)}")
        else:
            fig_learning(figs, load(lp), source, Used(rel(lp)))
    r1, r3 = find(cautionary, "backtest-upworthy-*.json"), find(run, "backtest-upworthy-*.json")
    if r1 is None or r3 is None:
        figs.skip("cautionary-upworthy.pdf", f"missing backtest-upworthy-*.json in {rel(cautionary) if r1 is None else rel(run)}")
    else:
        fig_cautionary(figs, r1, r3)
    figs.write_index(run, cautionary)
    return figs


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--run", default=os.path.join(ROOT, DEFAULT_RUN), help="run folder holding backtest-*.json and learning-curve-*.json")
    ap.add_argument("--out", default=os.path.join(ROOT, DEFAULT_OUT), help="output folder")
    ap.add_argument("--cautionary", default=None, help="run 1 folder (default: run-relative-lift beside the run folder)")
    a = ap.parse_args(argv)
    caut = a.cautionary or os.path.join(os.path.dirname(os.path.abspath(a.run)), "run1-relative-lift")
    build(a.run, a.out, caut)
    return 0


