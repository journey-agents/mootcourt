        snapshot_id=sid,
        guard_seeds=range(args.guard_seeds),
        guard_tests=args.guard_tests,
        tail_sizes=[int(s) for s in args.tail_sizes.split(",") if s],
        tail_top_m=args.tail_top_m,
        tail_queries=args.tail_queries,
        tail_seed=args.tail_seed,
        verbose=args.verbose,
        sensitivity_seeds=range(args.sensitivity_seeds),
