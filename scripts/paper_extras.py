def impressions_effect_correlation(ledger: pd.DataFrame, source: str) -> dict:
    """Correlation of log planned exposure per arm with ``|y / s|`` and with the significant-positive event, admitted rows of ``source``."""
    adm = ledger[(ledger["source"] == source) & (ledger["status"] == ADMITTED)]
    if adm.empty:
        raise ValueError(f"the ledger has no admitted rows for source {source}")
    exposure = 0.5 * (adm["n_ref"].to_numpy(float) + adm["n_var"].to_numpy(float))
    x = np.log(exposure)
    z = adm["y"].to_numpy(float) / adm["s"].to_numpy(float)
    out = {
        "n_rows": int(len(adm)),
        "corr_log_impressions_abs_z": float(np.corrcoef(x, np.abs(z))[0, 1]),
        "corr_log_impressions_event": float(np.corrcoef(x, (z > Z).astype(float))[0, 1]),
        "inputs": {
            "ledger_source": source,
            "rows": "status == admitted",
            "columns": ["n_ref", "n_var", "y", "s"],
            "exposure": "mean of n_ref and n_var, natural log",
            "event": f"y / s > {Z}",
        },
    }
    lengths = np.array([json.loads(j).get("final_offset_days") if j else None for j in adm["features_json"]], dtype=object)
    ok = np.array([isinstance(v, (int, float)) and v > 0 for v in lengths])
    if ok.sum() >= 3:
        run = np.log(lengths[ok].astype(float))
        out["corr_log_run_length_abs_z"] = float(np.corrcoef(run, np.abs(z[ok]))[0, 1])
        out["n_rows_with_run_length"] = int(ok.sum())
        out["inputs"]["run_length"] = "final_offset_days of the row's features (days from the start to the last checkpoint), natural log"
    return out


def guard_admission_rates(
    seeds, n_tests: int = 300, multipliers=GUARD_MULTIPLIERS, text_effect_strength: float = 0.0, variants_per_test: int = 2, verbose: bool = False
) -> dict:
    """Cells where P2 selects a positive precedent weight on synthetic data without a text signal, per guard multiplier and unguarded."""
    from mootcourt.features import FeatureSpace
    from mootcourt.predictors.p1 import P1Predictor
    from mootcourt.predictors.p2 import P2Predictor
    from mootcourt.sources import synthetic

    seeds = [int(s) for s in seeds]
    arms: list = [float(m) for m in multipliers] + ["off"]
    counts = {a: {"cells": 0, "admitted": 0} for a in arms}
    for seed in seeds:
        ledger, _ = synthetic.generate(
            synthetic.SyntheticConfig(seed=seed, n_tests=n_tests, variants_per_test=variants_per_test, text_effect_strength=text_effect_strength)
        )
        space = FeatureSpace.fit(ledger)
        p1 = P1Predictor().fit(ledger)
        for arm in arms:
            p2 = P2Predictor().fit(ledger, space, p1, guard=None if arm == "off" else arm)
            rows = p2.selection_summary()
            counts[arm]["cells"] += len(rows)
            counts[arm]["admitted"] += sum(1 for r in rows if r["lambda"] > 0.0)
        if verbose:
            print(f"guard admission: seed {seed} done", file=sys.stderr)
    by = [
        {
            "multiplier": a,
            **c,
            "share_admitted": c["admitted"] / c["cells"] if c["cells"] else None,
            "share_lambda_zero": 1.0 - c["admitted"] / c["cells"] if c["cells"] else None,
        }
        for a, c in counts.items()
    ]
    return {
        "by_multiplier": by,
        "inputs": {
            "generator": "mootcourt.sources.synthetic.generate (SyntheticConfig)",
            "seeds": seeds,
            "n_tests": int(n_tests),
            "variants_per_test": int(variants_per_test),
            "text_effect_strength": float(text_effect_strength),
            "p2": "P2Predictor().fit(ledger, FeatureSpace.fit(ledger), P1Predictor().fit(ledger), guard=multiplier); "
            "admitted = selected lambda above zero in a cell; off = guard=None, the earlier rule",
        },
    }


SENSITIVITY_STRENGTHS = (0.0, 0.5, 1.0, 2.0, 4.0)
SENSITIVITY_SIZES = (300, 1000, 11100)  # 11100 tests x 2 variants over 3 cells = about 7400 rows per cell (the Upworthy headline-only cell)


def positive_control_sensitivity(
    strengths=SENSITIVITY_STRENGTHS, sizes=SENSITIVITY_SIZES, seeds=range(12), multiplier: float = 2.0, verbose: bool = False
) -> dict:
    """Share of cells with a positive selected weight, by planted text strength and ledger size (two variants per test)."""
    from mootcourt.sources.synthetic import SyntheticConfig

    taus = {c: p[1] for c, p in SyntheticConfig().cell_params.items()}
    rows = []
    for n in sizes:
        for st in strengths:
            got = guard_admission_rates(seeds, int(n), multipliers=(multiplier,), text_effect_strength=float(st))
            by = got["by_multiplier"][0]
            rows.append(
                {
                    "n_tests": int(n),
                    "rows_per_cell": round(2.0 * int(n) / len(taus)),
                    "text_effect_strength": float(st),
                    "strength_over_prior_sd": {c: float(st) / t for c, t in taus.items()},
                    "cells": by["cells"],
                    "admitted": by["admitted"],
                    "share_admitted": by["share_admitted"],
                }
            )
            if verbose:
                print(f"sensitivity: n {n}, strength {st}: share admitted {by['share_admitted']:.3f}", file=sys.stderr)
    return {
        "rows": rows,
        "multiplier": float(multiplier),
        "inputs": {
            "seeds": [int(x) for x in seeds],
            "variants_per_test": 2,
            "cells": "the default synthetic cells and their tau",
            "tau_by_cell": taus,
        },
    }


GAIN_DIAGNOSTIC_SIZES = (300, 1000, 3700, 11100)


def guard_gain_diagnostic(sizes=GAIN_DIAGNOSTIC_SIZES, seeds=range(12), multiplier: float = 2.0, verbose: bool = False) -> dict:
    """In-selection gain, its standard error, their ratio and the share admitted, per ledger size, at planted lift zero (no signal)."""
    from mootcourt.features import FeatureSpace
    from mootcourt.predictors.p1 import P1Predictor
    from mootcourt.predictors.p2 import P2Predictor
    from mootcourt.sources import synthetic

    rows = []
    for n in sizes:
        gains, ses, adm, rows_cell = [], [], [], []
        for seed in [int(s) for s in seeds]:
            ledger, _ = synthetic.generate(synthetic.SyntheticConfig(seed=seed, n_tests=int(n), variants_per_test=2, text_effect_strength=0.0))
            p2 = P2Predictor().fit(ledger, FeatureSpace.fit(ledger), P1Predictor().fit(ledger), guard=multiplier)
            for r in p2.selection_summary():
                if r.get("gain") is None or r.get("gain_se") is None:
                    continue
                gains.append(r["gain"])
                ses.append(r["gain_se"])
                adm.append(r["lambda"] > 0.0)
                rows_cell.append(r["n_rows"])
        g, s, a = np.array(gains), np.array(ses), np.array(adm)
        rows.append(
            {
                "n_tests": int(n),
                "rows_per_cell": float(np.mean(rows_cell)),
                "cells": int(len(g)),
                "mean_gain": float(g.mean()),
                "mean_gain_se": float(s.mean()),
                "mean_ratio": float((g / s).mean()),
                "ratio_of_means": float(g.mean() / s.mean()),
                "share_gain_positive": float((g > 0).mean()),
                "share_admitted": float(a.mean()),
                "mean_gain_admitted": float(g[a].mean()) if a.any() else None,
                "mean_gain_not_admitted": float(g[~a].mean()) if (~a).any() else None,
            }
        )
        if verbose:
            print(f"gain diagnostic: n {n}: gain {g.mean():.5f}, se {s.mean():.5f}, admitted {a.mean():.2f}", file=sys.stderr)
    return {
        "rows": rows,
        "multiplier": float(multiplier),
        "inputs": {
            "seeds": [int(x) for x in seeds],
            "planted_text_effect": 0.0,
            "variants_per_test": 2,
            "gain": "best candidate lambda above zero (the one the guard tests): mean per-row log-score gain over lambda 0, leave-one-test-out rows",
            "rows_per_cell": "mean visible rows of the cell at the fit",
        },
    }


def _heldout_gain(p2, p1, space, held: pd.DataFrame, cell: str, origin) -> tuple[float, float | None]:
    """Mean log-score gain of P2 (its fitted weight) over P1 on the held-out rows of one cell, nats per row, with its standard error clustered by
    test; ``(0, None)`` where the weight is zero or the cell has no held-out rows."""
    rows = held[held["cell"] == cell]
    if rows.empty or p2._lam(cell) <= 0.0:
        return 0.0, None
    X = space.transform(rows)
    y, s = rows["y"].to_numpy(float), rows["s"].to_numpy(float)
    d = np.array(
        [
            p2.predict(X[i], s[i], cell, origin).logscore(y[i], s[i]) - p1.predict(X[i], s[i], cell, origin).logscore(y[i], s[i])
            for i in range(len(rows))
        ]
    )
    return float(d.mean()), _clustered_se(d, rows["test_id"].to_numpy())


def _clustered_se(d: np.ndarray, test_ids) -> float | None:
    """Standard error of the mean of ``d`` with rows clustered by test (the ratio estimator's linearization)."""
    codes, uniq = pd.factorize(test_ids)
    t = len(uniq)
    if t < 2:
        return None
    n_t = np.bincount(codes, minlength=t).astype(float)
    g_t = np.bincount(codes, weights=d - d.mean(), minlength=t)
    return float(np.sqrt(t / (t - 1) * np.sum(g_t**2)) / n_t.sum())


def split_tests(ledger: pd.DataFrame, seed: int, share: float = 0.15) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Fit and held-out rows: a random ``share`` of the TESTS is held out, never rows (the rows of a test share its effect)."""
    tests = np.array(sorted(ledger["test_id"].unique()))
    held = set(np.random.default_rng(seed).choice(tests, size=max(1, int(round(share * len(tests)))), replace=False))
    is_held = ledger["test_id"].isin(held)
    return ledger[~is_held], ledger[is_held]


def guard_held_out_gain(
    sizes=GAIN_DIAGNOSTIC_SIZES, seeds=range(12), multiplier: float = 2.0, held_share: float = 0.15, verbose: bool = False
) -> dict:
    """In-selection gain against the gain on held-out tests, per ledger size, with no planted signal.

    A random ``held_share`` of the TESTS (never rows) is held out and P2 is fit on the rest. Two comparisons, in every cell:

    * the BIAS of the selection: the in-selection gain of the best positive-weight candidate (its weight, bandwidth and half-life) against the
      held-out gain of that same candidate, whatever the guard chose (``mean_bias``, over all cells, and over the cells the guard admitted);
    * what the guard did: the held-out gain of the weight it CHOSE (zero where it held the weight at zero), over all cells and over the admitted ones.

    A second fit without the guard gives the bias of the unguarded choice. Standard errors of the held-out means are clustered by test."""
    from mootcourt.features import FeatureSpace
    from mootcourt.predictors.p1 import P1Predictor
    from mootcourt.predictors.p2 import P2Predictor
    from mootcourt.sources import synthetic

    out = []
    for n in sizes:
        rec = {k: [] for k in ("ins", "cand_held", "cand_se", "chosen_held", "chosen_se", "adm", "ins_u", "held_u")}
        skipped = 0
        for seed in [int(s) for s in seeds]:
            ledger, _ = synthetic.generate(synthetic.SyntheticConfig(seed=seed, n_tests=int(n), variants_per_test=2, text_effect_strength=0.0))
            ledger = ledger[ledger["status"] == "admitted"]
            fit_rows, held_rows = split_tests(ledger, seed, held_share)
            origin = ledger["usable_after"].max() + pd.Timedelta(days=1)
            space, p1 = FeatureSpace.fit(fit_rows), P1Predictor().fit(fit_rows)
            guarded = P2Predictor().fit(fit_rows, space, p1, guard=multiplier)
            for r in guarded.selection_summary():
                cell, top = r["cell"], guarded.top_candidate_by_cell.get(r["cell"])
                if r.get("gain") is None or top is None:
                    continue
                if not (held_rows["cell"] == cell).any():  # nothing held out in this cell: no bias to measure, not a zero
                    skipped += 1
                    continue
                rec["ins"].append(r["gain"])
                rec["adm"].append(r["lambda"] > 0.0)
                g, se = _heldout_gain(guarded, p1, space, held_rows, cell, origin)
                rec["chosen_held"].append(g)
                rec["chosen_se"].append(se)
                cell_rows = fit_rows[fit_rows["cell"] == cell]  # the best candidate, refit for this cell alone
                cand = P2Predictor().fit(
                    cell_rows,
                    space,
                    p1,
                    lambda_override=top["lambda"],
                    bandwidth_override=top["bandwidth_mult"],
                    recency=None if math.isinf(top["half_life_days"]) else top["half_life_days"],
                    guard=None,
                )
                g, se = _heldout_gain(cand, p1, space, held_rows, cell, origin)
                rec["cand_held"].append(g)
                rec["cand_se"].append(se)
            unguarded = P2Predictor().fit(fit_rows, space, p1, guard=None)
            for r in unguarded.selection_summary():
                if r.get("gain") is not None and r["lambda"] > 0.0 and (held_rows["cell"] == r["cell"]).any():
                    rec["ins_u"].append(r["gain"])
                    rec["held_u"].append(_heldout_gain(unguarded, p1, space, held_rows, r["cell"], origin)[0])
        i, ch, ca, a = (np.array(rec[k], float) for k in ("ins", "chosen_held", "cand_held", "adm"))
        a = a.astype(bool)
        n_cells = max(len(i), 1)

        def se_mean(xs, n_cells=n_cells):
            return float(np.sqrt(np.nansum(np.array([x for x in xs if x is not None], float) ** 2)) / n_cells)

        mean = lambda x: float(np.mean(x)) if len(x) else None  # noqa: E731
        out.append(
            {
                "n_tests": int(n),
                "cells": int(len(i)),
                "cells_skipped_without_held_out_rows": int(skipped),
                "mean_in_selection_gain": mean(i),
                "mean_candidate_held_out_gain": mean(ca),
                "mean_candidate_held_out_se": se_mean(rec["cand_se"]),
                "mean_bias": mean(i - ca),
                "mean_chosen_held_out_gain": mean(ch),
                "mean_chosen_held_out_se": se_mean(rec["chosen_se"]),
                "admitted_cells": int(a.sum()),
                "admitted_mean_in_selection_gain": mean(i[a]),
                "admitted_mean_candidate_held_out_gain": mean(ca[a]),
                "admitted_mean_bias": mean((i - ca)[a]),
                "admitted_mean_chosen_held_out_gain": mean(ch[a]),
                "unguarded_cells_with_weight": int(len(rec["ins_u"])),
                "unguarded_mean_in_selection_gain": mean(rec["ins_u"]),
                "unguarded_mean_held_out_gain": mean(rec["held_u"]),
                "unguarded_mean_bias": mean(np.array(rec["ins_u"]) - np.array(rec["held_u"])) if rec["ins_u"] else None,
            }
        )
        if verbose:
            print(f"held-out gain: n {n}: bias {out[-1]['mean_bias']:.5f}, chosen held-out {mean(ch):.5f}, admitted {int(a.sum())}", file=sys.stderr)
    return {
        "rows": out,
        "multiplier": float(multiplier),
        "held_out_share_of_tests": held_share,
        "inputs": {
            "seeds": [int(x) for x in seeds],
            "planted_text_effect": 0.0,
            "held_out": "a random share of the tests, never rows",
            "candidate": "the best positive-weight candidate (weight, bandwidth, half-life), refit alone for its cell, scored on held-out rows",
            "held_out_gain": "mean per-row log score of P2 minus P1 on the held-out rows, nats; its standard error is clustered by test",
            "standard_errors": "root of the sum of squared per-cell standard errors over the number of cells (cells independent)",
        },
    }


PERIOD_CONTROL_SIZES = (3700, 11100)


def guard_period_control(sizes=PERIOD_CONTROL_SIZES, seeds=range(12), multiplier: float = 2.0, verbose: bool = False) -> dict:
    """The guard's admissions at planted lift zero under three treatments of P1's period level (review N2, REV-N2-001).

    * ``old_rule``: every period counts, including a partial tail period (the rule before method call 199), P1 as fitted;
    * ``old_rule_no_period``: the old rule with every period replaced by the global fit, so P1 carries no period deviation;
    * ``new_rule``: the period level comes from the last complete period only (call 199).

    If the admissions of the old rule are P1's error on a thin latest period, they vanish when the deviation is removed and under the new rule."""
    from mootcourt.features import FeatureSpace
    from mootcourt.predictors.p1 import P1Predictor
    from mootcourt.predictors.p2 import P2Predictor
    from mootcourt.sources import synthetic

    def make_p1(arm: str, rows: pd.DataFrame) -> P1Predictor:
        if arm == "new_rule":
            return P1Predictor().fit(rows)
        p1 = P1Predictor().fit(rows, data_end=pd.Timestamp("2100-01-01", tz="UTC"))  # every period counts
        if arm == "old_rule_no_period":
            p1._period = {k: dict(p1._global) for k in p1._period}
            p1._cache = {}
        return p1

    arms = ("old_rule", "old_rule_no_period", "new_rule")
    out = []
    for n in sizes:
        acc = {a: {"gain": [], "se": [], "adm": [], "last_rows": []} for a in arms}
        for seed in [int(s) for s in seeds]:
            ledger, _ = synthetic.generate(synthetic.SyntheticConfig(seed=seed, n_tests=int(n), variants_per_test=2, text_effect_strength=0.0))
            adm_rows = ledger[ledger["status"] == "admitted"]
            space = FeatureSpace.fit(adm_rows)
            for a in arms:
                p1 = make_p1(a, adm_rows)
                p2 = P2Predictor().fit(adm_rows, space, p1, guard=multiplier)
                lp = p1.last_period()
                acc[a]["last_rows"].append(
                    0 if a == "old_rule_no_period" else (p1._period[lp]["n"] if lp in p1._period else 0)
                )  # no period level at all
                for r in p2.selection_summary():
                    if r.get("gain") is None:
                        continue
                    acc[a]["gain"].append(r["gain"])
                    acc[a]["se"].append(r["gain_se"])
                    acc[a]["adm"].append(r["lambda"] > 0.0)
            if verbose:
                print(f"period control: n {n} seed {seed} done", file=sys.stderr)
        for a in arms:
            g, s, d = np.array(acc[a]["gain"]), np.array(acc[a]["se"]), np.array(acc[a]["adm"])
            out.append(
                {
                    "n_tests": int(n),
                    "arm": a,
                    "cells": int(len(g)),
                    "mean_gain": float(g.mean()),
                    "mean_gain_se": float(s.mean()),
                    "ratio_of_means": float(g.mean() / s.mean()),
                    "share_gain_positive": float((g > 0).mean()),
                    "share_admitted": float(d.mean()),
                    "mean_rows_in_period_level": float(np.mean(acc[a]["last_rows"])),
                }
            )
    return {
        "rows": out,
        "multiplier": float(multiplier),
        "inputs": {
            "seeds": [int(x) for x in seeds],
            "planted_text_effect": 0.0,
            "variants_per_test": 2,
            "old_rule": "P1 fit with every period counted (data_end far in the future)",
            "old_rule_no_period": "the old rule with the period fit of every period replaced by the global fit",
            "new_rule": "P1 fit with the default data end (the newest usable_after): partial tail periods set no level",
            "mean_rows_in_period_level": "rows of the period whose level P1 adds to every cell at the fit date (0: none, as in the no-period arm)",
        },
    }


FRACTIONS = (0.85, 0.90, 0.95, 1.00)


def guard_fit_fraction_stability(n_tests: int = 3700, seeds=range(12), multiplier: float = 2.0, verbose: bool = False) -> dict:
    """Share of cells admitted when the same ledgers are fit on the first f of the rows in time order, and on a random 85 percent."""
    from mootcourt.features import FeatureSpace
    from mootcourt.predictors.p1 import P1Predictor
    from mootcourt.predictors.p2 import P2Predictor
    from mootcourt.sources import synthetic

    arms = [(f"first_{int(round(100 * f))}_percent", f, "time") for f in FRACTIONS] + [("random_85_percent", 0.85, "random")]
    counts = {name: [0, 0] for name, _, _ in arms}
    for seed in [int(s) for s in seeds]:
        ledger, _ = synthetic.generate(synthetic.SyntheticConfig(seed=seed, n_tests=int(n_tests), variants_per_test=2, text_effect_strength=0.0))
        adm_rows = ledger[ledger["status"] == "admitted"].sort_values("usable_after")
        for name, f, mode in arms:
            fit_rows = (
                adm_rows.iloc[: int(len(adm_rows) * f)] if mode == "time" else adm_rows.sample(frac=f, random_state=seed).sort_values("usable_after")
            )
            p2 = P2Predictor().fit(fit_rows, FeatureSpace.fit(fit_rows), P1Predictor().fit(fit_rows), guard=multiplier)
            rows = p2.selection_summary()
            counts[name][0] += len(rows)
            counts[name][1] += sum(1 for r in rows if r["lambda"] > 0.0)
        if verbose:
            print(f"fit fraction stability: seed {seed} done", file=sys.stderr)
    return {
        "n_tests": int(n_tests),
        "multiplier": float(multiplier),
        "rows": [
            {
                "fit": name,
                "fraction": f,
                "order": mode,
                "cells": counts[name][0],
                "admitted": counts[name][1],
                "share_admitted": counts[name][1] / counts[name][0] if counts[name][0] else None,
            }
            for name, f, mode in arms
        ],
        "inputs": {
            "seeds": [int(x) for x in seeds],
            "planted_text_effect": 0.0,
            "note": "11,100 tests was not run: each fit takes minutes at that size",
        },
    }


def _tail_ledger(n: int, experiments_dir: Path | None) -> tuple[pd.DataFrame, str, str]:
    """The synthetic ledger of ``n`` contrasts: the scale ledger on the data root when there is one, else a regenerated one."""
    from mootcourt.benchmark import DEFAULT_SEED, make_scale_ledger

    path = None if experiments_dir is None else Path(experiments_dir) / "scale" / f"ledger-{n}.parquet"
    if path is not None and path.exists():
        return read_ledger(path), "experiments/scale", str(path)
    return make_scale_ledger(n, DEFAULT_SEED), "generated", f"benchmark.make_scale_ledger({n}, seed={DEFAULT_SEED})"


def _summary(values: list[float]) -> dict:
    a = np.asarray(values, float)
    return {"mean": float(a.mean()), "p10": float(np.percentile(a, 10)), "p90": float(np.percentile(a, 90))}


def top_m_tail_share(
    sizes=TAIL_SIZES,
    top_m: int = TOP_M_NEIGHBORS,
    n_queries: int = 60,
    seed: int = 0,
    experiments_dir: Path | None = None,
    verbose: bool = False,
    n_seeds: int = 6,
) -> dict:
    """Share of the neighbor weight beyond the top ``top_m`` for ``n_queries`` headline-only queries, per ledger size.

    The queries are drawn with ``n_seeds`` seeds (``seed`` to ``seed + n_seeds - 1``), ``n_queries`` each, and the report gives the mean over
    all of them and the range of the per-seed means (``mean_range_over_seeds``): one seed is noise, and a single draw can sit at the edge
    of that range (round 00 review J).
    """
    from mootcourt.bundle import fit_bundle

    rng_seed = int(seed)
    out = []
    for n in [int(s) for s in sizes]:
        t0 = time.perf_counter()
        ledger, kind, where = _tail_ledger(n, experiments_dir)
        bundle = fit_bundle(ledger, "synthetic", f"paper-extras-{n}")
        origin = pd.Timestamp(ledger["usable_after"].max()) + pd.Timedelta(days=1)
        p2 = bundle.p2
        saved, p2.top_m = p2.top_m, None  # list every neighbor, then take the top M here
        raw, weighted, visible, raw_by_seed, w_by_seed = [], [], [], [], []
        try:
            for sd in range(rng_seed, rng_seed + int(n_seeds)):
                rng = np.random.default_rng(sd)
                r_s, w_s = [], []
                for i in range(n_queries):
                    headline = " ".join(rng.choice(TAIL_WORDS, size=int(rng.integers(3, 9)), replace=True)) + f" {i}"
                    x = bundle.transform_text(headline, False, cell=TAIL_CELL, exposure=int(rng.integers(5000, 60000)))
                    st = p2.neighbor_state(x, TAIL_CELL, origin.to_pydatetime())
                    kernel = np.asarray(st.kernel, float)
                    w = kernel / (np.asarray(st.s, float) ** 2 + st.tau**2)
                    k = len(kernel)
                    top = np.arange(k) if top_m >= k else np.argpartition(-kernel, top_m - 1)[:top_m]
                    r_s.append(1.0 - kernel[top].sum() / kernel.sum())
                    w_s.append(1.0 - w[top].sum() / w.sum())
                    visible.append(k)
                raw += r_s
                weighted += w_s
                raw_by_seed.append(float(np.mean(r_s)))
                w_by_seed.append(float(np.mean(w_s)))
        finally:
            p2.top_m = saved
        out.append(
            {
                "contrasts": n,
                "n_queries": int(n_queries),
                "n_visible_neighbors_mean": float(np.mean(visible)),
                "share_raw_kernel": _summary(raw),
                "share_p2_weight": _summary(weighted),
                "n_query_seeds": int(n_seeds),
                "mean_range_over_seeds": {
                    "share_raw_kernel": [min(raw_by_seed), max(raw_by_seed)],
                    "share_p2_weight": [min(w_by_seed), max(w_by_seed)],
                },
                "ledger": kind,
                "ledger_input": where,
                "bundle_rows": int(bundle.n_rows),
                "seconds": round(time.perf_counter() - t0, 1),
            }
        )
        if verbose:
            print(
                f"tail share at {n} contrasts: p2 weight {out[-1]['share_p2_weight']['mean']:.3f}, "
                f"raw kernel {out[-1]['share_raw_kernel']['mean']:.3f} ({out[-1]['seconds']} s)",
                file=sys.stderr,
            )
    return {
        "top_m": int(top_m),
        "cell": TAIL_CELL,
        "by_size": out,
        "inputs": {
            "queries": "random headlines of 3 to 8 words from the benchmark word list, no image change, planned exposure 5000 to 60000",
            "seeds": list(range(rng_seed, rng_seed + int(n_seeds))),
            "bundle": "fit_bundle on the whole ledger",
            "origin": "one day after the last usable_after",
        },
    }


def trigger_ablation_released_rows(reports_dir: Path, source: str, snapshot_id: str) -> dict:
    """Released-row scores of every single-trigger run of the snapshot that exists under ``reports/ablations``."""
    from mootcourt import harness_stats as hs

    reports_dir = Path(reports_dir)
    main_json = reports_dir / f"backtest-{source}-{snapshot_id}.json"
    main = json.loads(main_json.read_text(encoding="utf-8")) if main_json.exists() else None

    def pick(doc: dict, key: str) -> dict | None:
        return next((r for r in doc["tables"][key] if r["cell"] == "ALL" and r["rung"] == "P2"), None)

    runs = []
    for name in TRIGGERS:
        report = reports_dir / "ablations" / f"backtest-{source}-{snapshot_id}--drop-trigger-{name}.json"
        if not report.exists():
            continue
        doc = json.loads(report.read_text(encoding="utf-8"))
        if doc["header"]["snapshot_id"] != snapshot_id:
            raise ValueError(f"{report} is on snapshot {doc['header']['snapshot_id']}, not {snapshot_id}")
        released = pick(doc, "released_rows") if doc["tables"].get("released_rows") else None
        origin = "report tables.released_rows"
        if released is None:
            main_s = reports_dir / f"scores-{source}-{snapshot_id}.parquet"
            abl_s = reports_dir / "ablations" / f"scores-{source}-{snapshot_id}--drop-trigger-{name}.parquet"
            if not (main_s.exists() and abl_s.exists()):
                continue
            rows = hs.released_rows(
                pd.read_parquet(main_s),
                pd.read_parquet(abl_s),
                _gates(main),
                B=int(doc["header"]["bootstrap_resamples"]),
                seed=int(doc["header"]["seed"]),
            )
            released = next(r for r in rows if r["cell"] == "ALL")
            origin = "score tables"
        agg = pick(doc, "aggregate")
        keep = ("n_nonabstained", "abstention_rate", "logscore_nonabstained", "brier_nonabstained", "direction_accuracy_nonabstained")
        runs.append(
            {
                "dropped_trigger": name,
                "report": report.name,
                "released": released,
                "released_from": origin,
                "issued_in_ablation": {k: agg.get(k) for k in keep},
                "issued_in_main": None if main is None else {k: pick(main, "aggregate").get(k) for k in keep},
            }
        )
    return {
        "rung": "P2",
        "cell": "ALL",
        "runs": runs,
        "main_report": main_json.name if main else None,
        "inputs": {"definition": "rows abstained in the main run and issued in the run without the trigger"},
    }


def guard_pairs(reports_dir: Path, source: str, snapshot_id: str, level: float = 0.9, B: int = 1000, seed: int = 0) -> dict | None:
    """Per (origin, cell) pair where the guard admitted a positive weight: in-selection gain, lambda and the realized P2 minus P1 log score.

    None when the main report or its score table is not on the data root. The realized difference is the mean over the rows of the pair
    scored at that origin of ``logscore(P2) - logscore(P1)`` (nats, the same row under both rungs); the pooled line resamples tests."""
    reports_dir = Path(reports_dir)
    rep = reports_dir / f"backtest-{source}-{snapshot_id}.json"
    sco = reports_dir / f"scores-{source}-{snapshot_id}.parquet"
    if not (rep.exists() and sco.exists()):
        return None
    doc = json.loads(rep.read_text(encoding="utf-8"))
    sel = doc["tables"].get("p2_selection") or []
    scores = pd.read_parquet(sco, columns=["row_id", "test_id", "cell", "origin", "rung", "logscore"])
    p1 = scores[scores["rung"] == "P1"].set_index("row_id")
    p2 = scores[scores["rung"] == "P2"].set_index("row_id")
    common = p2.index.intersection(p1.index)
    diff = pd.DataFrame(
        {
            "test_id": p2.loc[common, "test_id"],
            "cell": p2.loc[common, "cell"],
            "origin": p2.loc[common, "origin"],
            "d": p2.loc[common, "logscore"] - p1.loc[common, "logscore"],
        }
    )
    diff["origin"] = pd.to_datetime(diff["origin"], utc=True)
    rows, parts = [], []
    for r in sel:
        if r.get("rung") != "P2" or not (r.get("lambda") or 0.0) > 0.0:
            continue
        origin = pd.Timestamp(r["origin"])
        origin = origin.tz_localize("UTC") if origin.tzinfo is None else origin.tz_convert("UTC")
        part = diff[(diff["cell"] == r["cell"]) & (diff["origin"] == origin)]
        parts.append(part)
        rows.append(
            {
                "origin": r["origin"],
                "cell": r["cell"],
                "lambda": r["lambda"],
                "lambda_unguarded": r.get("lambda_unguarded"),
                "in_selection_gain": r.get("gain"),
                "in_selection_gain_se": r.get("gain_se"),
                "n_visible_rows": r.get("n_rows"),
                "n_scored_rows": int(len(part)),
                "n_scored_tests": int(part["test_id"].nunique()),
                "realized_p2_minus_p1": float(part["d"].mean()) if len(part) else None,
            }
        )
    pooled = pd.concat(parts) if parts else diff.iloc[:0]
    summary = {
        "pairs_in_selection": int(sum(1 for r in sel if r.get("rung") == "P2")),
        "pairs_admitted": len(rows),
        "pairs_with_negative_realized": int(sum(1 for r in rows if r["realized_p2_minus_p1"] is not None and r["realized_p2_minus_p1"] < 0)),
        "mean_in_selection_gain": float(np.mean([r["in_selection_gain"] for r in rows if r["in_selection_gain"] is not None]))
        if any(r["in_selection_gain"] is not None for r in rows)
        else None,
    }
    if len(pooled):
        g = pooled.groupby("test_id")["d"].agg(["sum", "count"])
        rng = np.random.default_rng(seed)
        k = rng.multinomial(len(g), np.full(len(g), 1.0 / len(g)), size=B).astype(float)
        draws = (k @ g["sum"].to_numpy()) / (k @ g["count"].to_numpy())
        a = (1.0 - level) / 2.0
        lo, hi = np.percentile(draws, [100 * a, 100 * (1 - a)])
        summary.update(
            {
                "pooled_realized_p2_minus_p1": float(pooled["d"].mean()),
                "pooled_lo": float(lo),
                "pooled_hi": float(hi),
                "pooled_rows": int(len(pooled)),
                "pooled_tests": int(len(g)),
                "level": level,
                "bootstrap_resamples": B,
            }
        )
    return {
        "rows": rows,
        "summary": summary,
        "inputs": {
            "selection": f"{rep.name} tables.p2_selection (lambda > 0)",
            "scores": sco.name,
            "unit": "nats per row of log score",
            "in_selection_gain": "mean per-row log-score gain over lambda 0 on the leave-one-test-out validation rows of the fit",
        },
    }


def cautionary_deciles(reports_dir: Path, source: str, snapshot_id: str) -> dict | None:
    """Deciles of the realized standard error on the cautionary (naive protocol) run; None when its score table is not on the data root."""
    path = Path(reports_dir) / "ablations" / f"scores-{source}-{snapshot_id}--effect-scale-relative+s-star-realized.parquet"
    if not path.is_file():
        return None
    s = pd.read_parquet(path)
    rows = []
    for rung in ("P1", "P2"):
        d = s[s["rung"] == rung].copy()
        d["dec"] = pd.qcut(d["s"], 10, labels=False)
        for dec, grp in d.groupby("dec"):
            rows.append(
                {
                    "rung": rung,
                    "decile": int(dec) + 1,
                    "n": int(len(grp)),
                    "s_med": float(grp["s"].median()),
                    "y_mean": float(grp["y"].mean()),
                    "event": float(grp["event"].mean()),
                    "p_sig": float(grp["p_sig"].mean()),
                    "cov90": float(((grp["y"] >= grp["lo90"]) & (grp["y"] <= grp["hi90"])).mean()),
                }
            )
    return {"rows": rows, "inputs": {"scores": path.name, "decile_of": "realized standard error s, pandas qcut into 10 bins"}}


