SCHEMA_VERSION = 1
GUARD_MULTIPLIERS = (1.0, 1.5, 2.0)
TAIL_SIZES = (10_000, 100_000, 300_000)
TAIL_CELL = "headline_only"
TAIL_WORDS = HEADLINE_WORDS                       # the benchmark's own list, imported so the inputs record is true
DIFFERENCES_FROM_DOCS = [
    "guard_admission_rates: the one-off runs behind the documentation left no report file, so the cells are refit here on ledgers "
    "regenerated with the same generator, text effect zero, 300 tests of two variants per seed; the seeds and the settings are in inputs",
    "top_m_tail_share: the ledgers of 1e4 and 3e5 contrasts were not kept, so they are regenerated by benchmark.make_scale_ledger with the "
    "benchmark's seed; 1e5 reads the scale ledger when it exists; the 60 queries are drawn here with the seed in inputs",
]


def impressions_effect_correlation(ledger: pd.DataFrame, source: str) -> dict:
    """Correlation of log planned exposure per arm with ``|y / s|`` and with the significant-positive event, admitted rows of ``source``."""
    adm = ledger[(ledger["source"] == source) & (ledger["status"] == ADMITTED)]
    if adm.empty:
        raise ValueError(f"the ledger has no admitted rows for source {source}")
    exposure = 0.5 * (adm["n_ref"].to_numpy(float) + adm["n_var"].to_numpy(float))
    x = np.log(exposure)
    z = adm["y"].to_numpy(float) / adm["s"].to_numpy(float)
    out = {
        "n_rows": int(len(adm)),
        "corr_log_impressions_abs_z": float(np.corrcoef(x, np.abs(z))[0, 1]),
        "corr_log_impressions_event": float(np.corrcoef(x, (z > Z).astype(float))[0, 1]),
        "inputs": {"ledger_source": source, "rows": "status == admitted", "columns": ["n_ref", "n_var", "y", "s"],
                   "exposure": "mean of n_ref and n_var, natural log", "event": f"y / s > {Z}"},
    }
    lengths = np.array([json.loads(j).get("final_offset_days") if j else None for j in adm["features_json"]], dtype=object)
    ok = np.array([isinstance(v, (int, float)) and v > 0 for v in lengths])
    if ok.sum() >= 3:
        run = np.log(lengths[ok].astype(float))
        out["corr_log_run_length_abs_z"] = float(np.corrcoef(run, np.abs(z[ok]))[0, 1])
        out["n_rows_with_run_length"] = int(ok.sum())
        out["inputs"]["run_length"] = "final_offset_days of the row's features (days from the start to the last checkpoint), natural log"
    return out


def guard_admission_rates(seeds, n_tests: int = 300, multipliers=GUARD_MULTIPLIERS, text_effect_strength: float = 0.0,
                          variants_per_test: int = 2, verbose: bool = False) -> dict:
    """Cells where P2 selects a positive precedent weight on synthetic data without a text signal, per guard multiplier and unguarded."""
    from mootcourt.features import FeatureSpace
    from mootcourt.predictors.p1 import P1Predictor
    from mootcourt.predictors.p2 import P2Predictor
    from mootcourt.sources import synthetic

    seeds = [int(s) for s in seeds]
    arms: list = [float(m) for m in multipliers] + ["off"]
    counts = {a: {"cells": 0, "admitted": 0} for a in arms}
    for seed in seeds:
        ledger, _ = synthetic.generate(synthetic.SyntheticConfig(seed=seed, n_tests=n_tests, variants_per_test=variants_per_test,
                                                                 text_effect_strength=text_effect_strength))
        space = FeatureSpace.fit(ledger)
        p1 = P1Predictor().fit(ledger)
        for arm in arms:
            p2 = P2Predictor().fit(ledger, space, p1, guard=None if arm == "off" else arm)
            rows = p2.selection_summary()
            counts[arm]["cells"] += len(rows)
            counts[arm]["admitted"] += sum(1 for r in rows if r["lambda"] > 0.0)
        if verbose:
            print(f"guard admission: seed {seed} done", file=sys.stderr)
    by = [{"multiplier": a, **c, "share_admitted": c["admitted"] / c["cells"] if c["cells"] else None,
           "share_lambda_zero": 1.0 - c["admitted"] / c["cells"] if c["cells"] else None} for a, c in counts.items()]
    return {
        "by_multiplier": by,
        "inputs": {"generator": "mootcourt.sources.synthetic.generate (SyntheticConfig)", "seeds": seeds, "n_tests": int(n_tests),
                   "variants_per_test": int(variants_per_test), "text_effect_strength": float(text_effect_strength),
                   "p2": "P2Predictor().fit(ledger, FeatureSpace.fit(ledger), P1Predictor().fit(ledger), guard=multiplier); "
                         "admitted = selected lambda above zero in a cell; off = guard=None, the earlier rule"},
    }


SENSITIVITY_STRENGTHS = (0.0, 0.5, 1.0, 2.0, 4.0)
SENSITIVITY_SIZES = (300, 1000, 3700)       # 3700 tests of two variants = 7400 rows, the size of the Upworthy headline-only cell


def positive_control_sensitivity(strengths=SENSITIVITY_STRENGTHS, sizes=SENSITIVITY_SIZES, seeds=range(12), multiplier: float = 2.0,
                                 verbose: bool = False) -> dict:
    """Share of cells with a positive selected weight, by planted text strength and ledger size (two variants per test)."""
    from mootcourt.sources.synthetic import SyntheticConfig

    taus = {c: p[1] for c, p in SyntheticConfig().cell_params.items()}
    rows = []
    for n in sizes:
        for st in strengths:
            got = guard_admission_rates(seeds, int(n), multipliers=(multiplier,), text_effect_strength=float(st))
            by = got["by_multiplier"][0]
            rows.append({"n_tests": int(n), "text_effect_strength": float(st), "strength_over_prior_sd": {c: float(st) / t for c, t in taus.items()},
                         "cells": by["cells"], "admitted": by["admitted"], "share_admitted": by["share_admitted"]})
            if verbose:
                print(f"sensitivity: n {n}, strength {st}: share admitted {by['share_admitted']:.3f}", file=sys.stderr)
    return {"rows": rows, "multiplier": float(multiplier),
            "inputs": {"seeds": [int(x) for x in seeds], "variants_per_test": 2, "cells": "the default synthetic cells and their tau",
                       "tau_by_cell": taus}}


def _tail_ledger(n: int, experiments_dir: Path | None) -> tuple[pd.DataFrame, str, str]:
    """The synthetic ledger of ``n`` contrasts: the scale ledger on the data root when there is one, else a regenerated one."""
    from mootcourt.benchmark import DEFAULT_SEED, make_scale_ledger

    path = None if experiments_dir is None else Path(experiments_dir) / "scale" / f"ledger-{n}.parquet"
    if path is not None and path.exists():
        return read_ledger(path), "experiments/scale", str(path)
    return make_scale_ledger(n, DEFAULT_SEED), "generated", f"benchmark.make_scale_ledger({n}, seed={DEFAULT_SEED})"


def _summary(values: list[float]) -> dict:
    a = np.asarray(values, float)
    return {"mean": float(a.mean()), "p10": float(np.percentile(a, 10)), "p90": float(np.percentile(a, 90))}


def top_m_tail_share(sizes=TAIL_SIZES, top_m: int = TOP_M_NEIGHBORS, n_queries: int = 60, seed: int = 0,
                     experiments_dir: Path | None = None, verbose: bool = False, n_seeds: int = 6) -> dict:
    """Share of the neighbor weight beyond the top ``top_m`` for ``n_queries`` headline-only queries, per ledger size.

    The queries are drawn with ``n_seeds`` seeds (``seed`` to ``seed + n_seeds - 1``), ``n_queries`` each, and the report gives the mean over
    all of them and the range of the per-seed means (``mean_range_over_seeds``): one seed is noise, and a single draw can sit at the edge
    of that range (round 00 review J).
    """
    from mootcourt.bundle import fit_bundle

    rng_seed = int(seed)
    out = []
    for n in [int(s) for s in sizes]:
        t0 = time.perf_counter()
        ledger, kind, where = _tail_ledger(n, experiments_dir)
        bundle = fit_bundle(ledger, "synthetic", f"paper-extras-{n}")
        origin = pd.Timestamp(ledger["usable_after"].max()) + pd.Timedelta(days=1)
        p2 = bundle.p2
        saved, p2.top_m = p2.top_m, None            # list every neighbor, then take the top M here
        raw, weighted, visible, raw_by_seed, w_by_seed = [], [], [], [], []
        try:
            for sd in range(rng_seed, rng_seed + int(n_seeds)):
                rng = np.random.default_rng(sd)
                r_s, w_s = [], []
                for i in range(n_queries):
                    headline = " ".join(rng.choice(TAIL_WORDS, size=int(rng.integers(3, 9)), replace=True)) + f" {i}"
                    x = bundle.transform_text(headline, False, cell=TAIL_CELL, exposure=int(rng.integers(5000, 60000)))
                    st = p2.neighbor_state(x, TAIL_CELL, origin.to_pydatetime())
                    kernel = np.asarray(st.kernel, float)
                    w = kernel / (np.asarray(st.s, float) ** 2 + st.tau**2)
                    k = len(kernel)
                    top = np.arange(k) if top_m >= k else np.argpartition(-kernel, top_m - 1)[:top_m]
                    r_s.append(1.0 - kernel[top].sum() / kernel.sum())
                    w_s.append(1.0 - w[top].sum() / w.sum())
                    visible.append(k)
                raw += r_s
                weighted += w_s
                raw_by_seed.append(float(np.mean(r_s)))
                w_by_seed.append(float(np.mean(w_s)))
        finally:
            p2.top_m = saved
        out.append({"contrasts": n, "n_queries": int(n_queries), "n_visible_neighbors_mean": float(np.mean(visible)),
                    "share_raw_kernel": _summary(raw), "share_p2_weight": _summary(weighted), "n_query_seeds": int(n_seeds),
                    "mean_range_over_seeds": {"share_raw_kernel": [min(raw_by_seed), max(raw_by_seed)],
                                              "share_p2_weight": [min(w_by_seed), max(w_by_seed)]}, "ledger": kind, "ledger_input": where,
                    "bundle_rows": int(bundle.n_rows), "seconds": round(time.perf_counter() - t0, 1)})
        if verbose:
            print(f"tail share at {n} contrasts: p2 weight {out[-1]['share_p2_weight']['mean']:.3f}, "
                  f"raw kernel {out[-1]['share_raw_kernel']['mean']:.3f} ({out[-1]['seconds']} s)", file=sys.stderr)
    return {"top_m": int(top_m), "cell": TAIL_CELL, "by_size": out,
            "inputs": {"queries": "random headlines of 3 to 8 words from the benchmark word list, no image change, planned exposure 5000 to 60000",
                       "seeds": list(range(rng_seed, rng_seed + int(n_seeds))), "bundle": "fit_bundle on the whole ledger",
                       "origin": "one day after the last usable_after"}}


def trigger_ablation_released_rows(reports_dir: Path, source: str, snapshot_id: str) -> dict:
    """Released-row scores of every single-trigger run of the snapshot that exists under ``reports/ablations``."""
    from mootcourt import harness_stats as hs

    reports_dir = Path(reports_dir)
    main_json = reports_dir / f"backtest-{source}-{snapshot_id}.json"
    main = json.loads(main_json.read_text(encoding="utf-8")) if main_json.exists() else None

    def pick(doc: dict, key: str) -> dict | None:
        return next((r for r in doc["tables"][key] if r["cell"] == "ALL" and r["rung"] == "P2"), None)

    runs = []
    for name in TRIGGERS:
        report = reports_dir / "ablations" / f"backtest-{source}-{snapshot_id}--drop-trigger-{name}.json"
        if not report.exists():
            continue
        doc = json.loads(report.read_text(encoding="utf-8"))
        if doc["header"]["snapshot_id"] != snapshot_id:
            raise ValueError(f"{report} is on snapshot {doc['header']['snapshot_id']}, not {snapshot_id}")
        released = pick(doc, "released_rows") if doc["tables"].get("released_rows") else None
        origin = "report tables.released_rows"
        if released is None:
            main_s = reports_dir / f"scores-{source}-{snapshot_id}.parquet"
            abl_s = reports_dir / "ablations" / f"scores-{source}-{snapshot_id}--drop-trigger-{name}.parquet"
            if not (main_s.exists() and abl_s.exists()):
                continue
            rows = hs.released_rows(pd.read_parquet(main_s), pd.read_parquet(abl_s), _gates(main),
                                    B=int(doc["header"]["bootstrap_resamples"]), seed=int(doc["header"]["seed"]))
            released = next(r for r in rows if r["cell"] == "ALL")
            origin = "score tables"
        agg = pick(doc, "aggregate")
        keep = ("n_nonabstained", "abstention_rate", "logscore_nonabstained", "brier_nonabstained", "direction_accuracy_nonabstained")
        runs.append({"dropped_trigger": name, "report": report.name, "released": released, "released_from": origin,
                     "issued_in_ablation": {k: agg.get(k) for k in keep},
                     "issued_in_main": None if main is None else {k: pick(main, "aggregate").get(k) for k in keep}})
    return {"rung": "P2", "cell": "ALL", "runs": runs, "main_report": main_json.name if main else None,
            "inputs": {"definition": "rows abstained in the main run and issued in the run without the trigger"}}


def guard_pairs(reports_dir: Path, source: str, snapshot_id: str, level: float = 0.9, B: int = 1000, seed: int = 0) -> dict | None:
    """Per (origin, cell) pair where the guard admitted a positive weight: in-selection gain, lambda and the realized P2 minus P1 log score.

    None when the main report or its score table is not on the data root. The realized difference is the mean over the rows of the pair
    scored at that origin of ``logscore(P2) - logscore(P1)`` (nats, the same row under both rungs); the pooled line resamples tests."""
    reports_dir = Path(reports_dir)
    rep = reports_dir / f"backtest-{source}-{snapshot_id}.json"
    sco = reports_dir / f"scores-{source}-{snapshot_id}.parquet"
    if not (rep.exists() and sco.exists()):
        return None
    doc = json.loads(rep.read_text(encoding="utf-8"))
    sel = doc["tables"].get("p2_selection") or []
    scores = pd.read_parquet(sco, columns=["row_id", "test_id", "cell", "origin", "rung", "logscore"])
    p1 = scores[scores["rung"] == "P1"].set_index("row_id")
    p2 = scores[scores["rung"] == "P2"].set_index("row_id")
    common = p2.index.intersection(p1.index)
    diff = pd.DataFrame({"test_id": p2.loc[common, "test_id"], "cell": p2.loc[common, "cell"], "origin": p2.loc[common, "origin"],
                         "d": p2.loc[common, "logscore"] - p1.loc[common, "logscore"]})
    diff["origin"] = pd.to_datetime(diff["origin"], utc=True)
    rows, parts = [], []
    for r in sel:
        if r.get("rung") != "P2" or not (r.get("lambda") or 0.0) > 0.0:
            continue
        origin = pd.Timestamp(r["origin"])
        origin = origin.tz_localize("UTC") if origin.tzinfo is None else origin.tz_convert("UTC")
        part = diff[(diff["cell"] == r["cell"]) & (diff["origin"] == origin)]
        parts.append(part)
        rows.append({"origin": r["origin"], "cell": r["cell"], "lambda": r["lambda"], "lambda_unguarded": r.get("lambda_unguarded"),
                     "in_selection_gain": r.get("gain"), "in_selection_gain_se": r.get("gain_se"), "n_visible_rows": r.get("n_rows"),
                     "n_scored_rows": int(len(part)), "n_scored_tests": int(part["test_id"].nunique()),
                     "realized_p2_minus_p1": float(part["d"].mean()) if len(part) else None})
    pooled = pd.concat(parts) if parts else diff.iloc[:0]
    summary = {"pairs_in_selection": int(sum(1 for r in sel if r.get("rung") == "P2")), "pairs_admitted": len(rows),
               "pairs_with_negative_realized": int(sum(1 for r in rows if r["realized_p2_minus_p1"] is not None and r["realized_p2_minus_p1"] < 0)),
               "mean_in_selection_gain": float(np.mean([r["in_selection_gain"] for r in rows if r["in_selection_gain"] is not None]))
               if any(r["in_selection_gain"] is not None for r in rows) else None}
    if len(pooled):
        g = pooled.groupby("test_id")["d"].agg(["sum", "count"])
        rng = np.random.default_rng(seed)
        k = rng.multinomial(len(g), np.full(len(g), 1.0 / len(g)), size=B).astype(float)
        draws = (k @ g["sum"].to_numpy()) / (k @ g["count"].to_numpy())
        a = (1.0 - level) / 2.0
        lo, hi = np.percentile(draws, [100 * a, 100 * (1 - a)])
        summary.update({"pooled_realized_p2_minus_p1": float(pooled["d"].mean()), "pooled_lo": float(lo), "pooled_hi": float(hi),
                        "pooled_rows": int(len(pooled)), "pooled_tests": int(len(g)), "level": level, "bootstrap_resamples": B})
    return {"rows": rows, "summary": summary,
            "inputs": {"selection": f"{rep.name} tables.p2_selection (lambda > 0)", "scores": sco.name, "unit": "nats per row of log score",
                       "in_selection_gain": "mean per-row log-score gain over lambda 0 on the leave-one-test-out validation rows of the fit"}}


def cautionary_deciles(reports_dir: Path, source: str, snapshot_id: str) -> dict | None:
    """Deciles of the realized standard error on the cautionary (naive protocol) run; None when its score table is not on the data root."""
    path = Path(reports_dir) / "ablations" / f"scores-{source}-{snapshot_id}--effect-scale-relative+s-star-realized.parquet"
    if not path.is_file():
        return None
    s = pd.read_parquet(path)
    rows = []
    for rung in ("P1", "P2"):
        d = s[s["rung"] == rung].copy()
        d["dec"] = pd.qcut(d["s"], 10, labels=False)
        for dec, grp in d.groupby("dec"):
            rows.append({"rung": rung, "decile": int(dec) + 1, "n": int(len(grp)), "s_med": float(grp["s"].median()),
                         "y_mean": float(grp["y"].mean()),
                         "event": float(grp["event"].mean()), "p_sig": float(grp["p_sig"].mean()),
                         "cov90": float(((grp["y"] >= grp["lo90"]) & (grp["y"] <= grp["hi90"])).mean())})
    return {"rows": rows, "inputs": {"scores": path.name, "decile_of": "realized standard error s, pandas qcut into 10 bins"}}


def _gates(main: dict | None) -> dict:
    h = (main or {}).get("header", {})
    return {"n_200": h.get("gate_n_200", 0), "n_400": h.get("gate_n_400", 0), "decision_target": h.get("gate_decision_target"),
            "by_target": h.get("gate_by_target") or {}}


def build_extras(source: str, ledger: pd.DataFrame, reports_dir, *, experiments_dir=None, snapshot_id: str, guard_seeds=range(24),
                 guard_tests: int = 300, tail_sizes=TAIL_SIZES, tail_top_m: int = TOP_M_NEIGHBORS, tail_queries: int = 60,
                 tail_seed: int = 0, verbose: bool = False, sensitivity_seeds=range(12), sensitivity_sizes=SENSITIVITY_SIZES) -> dict:
    """The paper-extras document of one source. The synthetic-ledger values are computed for the synthetic source only."""
    reports_dir = Path(reports_dir)
    main_json = reports_dir / f"backtest-{source}-{snapshot_id}.json"
    header = {
        "source": source, "snapshot_id": snapshot_id, "main_report": main_json.name if main_json.exists() else None,
        "created_by": "scripts/paper_extras.py", "created_at": dt.datetime.now(dt.timezone.utc).isoformat(),
        "schema_version": SCHEMA_VERSION, "differences_from_docs": DIFFERENCES_FROM_DOCS,
    }
    doc: dict = {"header": header, "impressions_effect_correlation": impressions_effect_correlation(ledger, source)}
    if source == "synthetic":
        doc["guard_admission_rates"] = guard_admission_rates(guard_seeds, guard_tests, verbose=verbose)
        doc["positive_control_sensitivity"] = (positive_control_sensitivity(sizes=sensitivity_sizes, seeds=sensitivity_seeds, verbose=verbose)
                                               if len(list(sensitivity_seeds)) else None)
        doc["top_m_tail_share"] = top_m_tail_share(tail_sizes, tail_top_m, tail_queries, tail_seed, experiments_dir, verbose=verbose)
    else:
        doc["guard_admission_rates"] = doc["top_m_tail_share"] = doc["positive_control_sensitivity"] = None
        header["not_computed_reason"] = ("guard_admission_rates and top_m_tail_share are properties of the method on synthetic data and "
                                         "are in the synthetic source's report")
    doc["trigger_ablation_released_rows"] = trigger_ablation_released_rows(reports_dir, source, snapshot_id)
    doc["guard_pairs"] = guard_pairs(reports_dir, source, snapshot_id)
    doc["cautionary_deciles"] = cautionary_deciles(reports_dir, source, snapshot_id)
    return clean(doc)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--source", required=True)
    paths = storage_paths()
    ap.add_argument("--ledger", default=str(paths.ledger_path))
    ap.add_argument("--reports-dir", default=str(paths.reports))
    ap.add_argument("--experiments-dir", default=str(paths.experiments))
    ap.add_argument("--guard-seeds", type=int, default=24, help="number of seeds (0 to N-1) for the guard admission rates")
    ap.add_argument("--guard-tests", type=int, default=300)
    ap.add_argument("--tail-sizes", default=",".join(str(n) for n in TAIL_SIZES), help="comma separated numbers of contrasts")
    ap.add_argument("--tail-top-m", type=int, default=TOP_M_NEIGHBORS)
    ap.add_argument("--tail-queries", type=int, default=60)
    ap.add_argument("--tail-seed", type=int, default=0)
    ap.add_argument("--sensitivity-seeds", type=int, default=12, help="number of seeds for the positive-control sensitivity (0 skips it)")
    ap.add_argument("--sensitivity-sizes", default=",".join(str(n) for n in SENSITIVITY_SIZES), help="comma separated numbers of tests")
    ap.add_argument("--verbose", action="store_true")
    args = ap.parse_args()
    ledger_path = Path(args.ledger)
    df = read_ledger(ledger_path)
    df = df[df["source"] == args.source].reset_index(drop=True)
    if df.empty:
        print(f"the ledger {ledger_path} has no rows for source {args.source}", file=sys.stderr)
        return 1
    sid = ensure_snapshot(df, ledger_path.parent)
    t0 = time.perf_counter()
    doc = build_extras(args.source, df, args.reports_dir, experiments_dir=args.experiments_dir, snapshot_id=sid,
                       guard_seeds=range(args.guard_seeds), guard_tests=args.guard_tests,
                       tail_sizes=[int(s) for s in args.tail_sizes.split(",") if s], tail_top_m=args.tail_top_m,
                       tail_queries=args.tail_queries, tail_seed=args.tail_seed, verbose=args.verbose,
                       sensitivity_seeds=range(args.sensitivity_seeds), sensitivity_sizes=[int(x) for x in args.sensitivity_sizes.split(",") if x])
    out = Path(args.reports_dir) / f"paper-extras-{args.source}-{sid}.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    tmp = out.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(doc, indent=1, sort_keys=True, allow_nan=False) + "\n", encoding="utf-8")
    tmp.replace(out)
    print(f"computed in {time.perf_counter() - t0:.1f} s")
    print(f"wrote {out}")
    return 0


