#!/usr/bin/env python3
"""Write ``<reports>/paper-extras-<source>-<snapshot>.json``: the paper numbers that no backtest report holds.

Every value is computed here from inputs on the data root or from the code, never copied from the documentation, and each value carries
the inputs it came from:

* ``impressions_effect_correlation``: on the admitted rows of the source, the correlation of the natural log of the planned exposure per
  arm (the mean of the two arms' impressions) with the absolute standardized effect ``|y / s|`` and with the significant-positive event
  (``y > 1.96 s``). Input: the ledger. Computed for every source, so the ASOS value (where the proxy is the user count at the final
  checkpoint of a run whose length varies) stands beside the Upworthy one; where the rows record the run length (``final_offset_days``,
  ASOS) the correlation of its logarithm with ``|y / s|`` is added, because on a platform with sequential stopping the realized count is an
  output of the stopping rule (round 00, R2).
* ``guard_admission_rates`` (synthetic source only): the share of cells in which the P2 admission guard still admits a positive precedent
  weight when the synthetic data carry no text signal, for each guard multiplier and for the earlier unguarded rule. Input: ledgers
  regenerated by ``mootcourt.sources.synthetic.generate`` with a text effect of zero, one per seed, and a fresh P2 fit per multiplier.
* ``positive_control_sensitivity`` (synthetic source only): the share of cells in which the guard (multiplier 2) admits a positive precedent
  weight when a text signal of each strength is planted, at two ledger sizes, with the strength in units of each cell's prior standard
  deviation. It answers "what is the smallest planted effect the guard can detect at these cell sizes" (round 00, R3). Input: ledgers
  regenerated by the synthetic generator.
* ``top_m_tail_share`` (synthetic source only): the share of the total weight of a query's neighbors that lies beyond the top M
  neighbors, for headline-only queries against a bundle fitted on a synthetic ledger of each size. Both the raw kernel weight and the P2
  weight (kernel divided by the row's variance plus the prior variance, what the card's moments use) are given. Input: the scale ledger
  under ``experiments/scale/`` when one of that size exists, otherwise a ledger regenerated by ``benchmark.make_scale_ledger``.
* ``guard_pairs``: for every (origin, cell) pair of the main run where the P2 guard admitted a positive precedent weight, the in-selection
  gain over lambda 0 (mean per validation row, nats) and its standard error, the chosen and the unguarded lambda, the rows and tests scored
  in the pair, and the realized out-of-time P2 minus P1 log score on those rows; plus the pooled realized difference over the admitted pairs
  with a 90 percent interval by test, so "in-selection gains do not transfer" is a table (review R3). Input: the main report's
  ``tables.p2_selection`` and the main run's score table.
* ``cautionary_deciles`` (when the cautionary run's score table exists): by decile of the realized standard error, the median s, mean y,
  event rate, mean p_sig and 90 percent coverage of P1 and P2 on the naive-protocol run (relative lift, realized s_star), so the
  cautionary table of the paper traces to a JSON. Input: ``ablations/scores-<source>-<snapshot>--effect-scale-relative+s-star-realized.parquet``.
* ``trigger_ablation_released_rows``: for each trigger-removal run of the snapshot on the data root, the scores of the rows the main run
  abstained on and the run issued. Input: the run's ``tables.released_rows`` (or, for a report written before that table existed, the
  two score tables).

Use: ``python scripts/paper_extras.py --source upworthy`` (and asos, synthetic). Nothing is written but the report.
"""
