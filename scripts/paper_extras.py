def build_extras(
    source: str,
    ledger: pd.DataFrame,
    reports_dir,
    *,
    experiments_dir=None,
    snapshot_id: str,
    guard_seeds=range(24),
    guard_tests: int = 300,
    tail_sizes=TAIL_SIZES,
    tail_top_m: int = TOP_M_NEIGHBORS,
    tail_queries: int = 60,
    tail_seed: int = 0,
    verbose: bool = False,
    sensitivity_seeds=range(12),
    sensitivity_sizes=SENSITIVITY_SIZES,
) -> dict:
    """The paper-extras document of one source. The synthetic-ledger values are computed for the synthetic source only."""
    reports_dir = Path(reports_dir)
    main_json = reports_dir / f"backtest-{source}-{snapshot_id}.json"
    header = {
        "source": source,
        "snapshot_id": snapshot_id,
        "main_report": main_json.name if main_json.exists() else None,
        "created_by": "scripts/paper_extras.py",
        "created_at": dt.datetime.now(dt.timezone.utc).isoformat(),
        "schema_version": SCHEMA_VERSION,
        "differences_from_docs": DIFFERENCES_FROM_DOCS,
    }
    doc: dict = {"header": header, "impressions_effect_correlation": impressions_effect_correlation(ledger, source)}
    if source == "synthetic":
        doc["guard_admission_rates"] = guard_admission_rates(guard_seeds, guard_tests, verbose=verbose)
        doc["positive_control_sensitivity"] = (
            positive_control_sensitivity(sizes=sensitivity_sizes, seeds=sensitivity_seeds, verbose=verbose) if len(list(sensitivity_seeds)) else None
        )
        seeds_on = len(list(sensitivity_seeds)) > 0
        doc["guard_gain_diagnostic"] = guard_gain_diagnostic(seeds=sensitivity_seeds, verbose=verbose) if seeds_on else None
        doc["guard_held_out_gain"] = guard_held_out_gain(seeds=sensitivity_seeds, verbose=verbose) if seeds_on else None
        doc["guard_fit_fraction_stability"] = guard_fit_fraction_stability(seeds=sensitivity_seeds, verbose=verbose) if seeds_on else None
        doc["guard_period_control"] = guard_period_control(seeds=sensitivity_seeds, verbose=verbose) if seeds_on else None
        doc["top_m_tail_share"] = top_m_tail_share(tail_sizes, tail_top_m, tail_queries, tail_seed, experiments_dir, verbose=verbose)
    else:
        doc["guard_admission_rates"] = doc["top_m_tail_share"] = doc["positive_control_sensitivity"] = doc["guard_gain_diagnostic"] = None
        doc["guard_held_out_gain"] = doc["guard_fit_fraction_stability"] = doc["guard_period_control"] = None
        header["not_computed_reason"] = (
            "guard_admission_rates and top_m_tail_share are properties of the method on synthetic data and are in the synthetic source's report"
        )
    doc["trigger_ablation_released_rows"] = trigger_ablation_released_rows(reports_dir, source, snapshot_id)
    doc["guard_pairs"] = guard_pairs(reports_dir, source, snapshot_id)
    doc["cautionary_deciles"] = cautionary_deciles(reports_dir, source, snapshot_id)
    return clean(doc)


