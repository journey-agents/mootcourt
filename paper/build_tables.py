"""Render the paper's LaTeX tables from Moot Court report JSON files.

Usage: python build_tables.py --reports "/Volumes/Crucial X10/mootcourt-data/reports" --out tables
Every table file starts with a comment naming the report file and snapshot id it came from, so each
number in the paper traces to one JSON path. No number is typed by hand.
"""

from __future__ import annotations

import argparse
import glob
import json
import os
import statistics


def f3(x, nd=3):
    return "" if x is None else f"{x:.{nd}f}"


def interval(r, key, nd=3):
    if r.get(key) is None:
        return ""
    return f"{f3(r[key], nd)} ({f3(r.get(key + '_lo'), nd)}, {f3(r.get(key + '_hi'), nd)})"


def challenger_rows(reports_dir, source):
    rows = []
    for fpath in sorted(glob.glob(os.path.join(reports_dir, "challengers", f"*{source}*.json"))):
        try:
            rep = load(fpath)
        except Exception:
            continue
        for r in rep.get("tables", {}).get("aggregate", []):
            if r.get("cell") == "ALL" and r.get("kind", "") not in ("ladder", "baseline"):
                r = dict(r)
                r["_file"] = os.path.basename(fpath)
                rows.append(r)
    return rows


def latest(pattern):
    files = sorted(glob.glob(pattern), key=os.path.getmtime)
    return files[-1] if files else None


def load(path):
    with open(path) as fh:
        return json.load(fh)


def esc(s):
    return str(s).replace("_", "\\_")


def write(out, name, header_comment, body):
    path = os.path.join(out, name)
    with open(path, "w") as fh:
        fh.write(f"% generated by paper/build_tables.py from {header_comment}\n")
        fh.write(body)
    print("wrote", path)


def main_table(rep, source, out):
    h, agg = rep["header"], rep["tables"]["aggregate"]
    rows = [r for r in agg if r["cell"] == "ALL"] + challenger_rows(os.path.dirname(rep["_path"]), source)
    lines = [
        r"\begin{tabular}{llrrrrrrrr}",
        r"\toprule",
        r"kind & model & tests & log score & CRPS & Brier skill (90\%) & dir.\ acc.\ / ceiling & cov.\ 80 / 90 & abst. & decid. \\",
        r"\midrule",
    ]
    for r in rows:
        dec = str(r.get("decidable_by_tests") or r.get("decidable") or "")
        dec = "yes" if dec.startswith("decidable at skill 0.20 and 0.10") else ("0.20 only" if "0.20 only" in dec else ("no" if dec else ""))
        lines.append(
            " & ".join(
                [
                    esc(r.get("kind", "rung")),
                    esc(r["rung"]),
                    str(r.get("n_tests", "")),
                    f3(r["logscore"]),
                    f3(r["crps"], 2),
                    interval(r, "brier_skill"),
                    f"{f3(r['direction_accuracy'])} / {f3(r.get('direction_ceiling'))}",
                    (f"{f3(r['coverage_80'], 2)} / {f3(r['coverage_90'], 2)}" if r.get("coverage_80") is not None else ""),
                    f3(r["abstention_rate"], 3),
                    dec,
                ]
            )
            + r" \\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    note = (
        f"source {source}, snapshot {h['snapshot_id']}, model {h['model_id']}, "
        f"{h['scored_rows']} scored rows over {h['origins_scored']} origins; "
        f"gate decision target {h.get('gate_decision_target')}"
    )
    write(out, f"main-{source}.tex", f"{rep['_path']} ({note})", "\n".join(lines) + "\n")


def calibration_table(rep, source, out, rungs=("P1", "P2")):
    t = rep["tables"].get("calibration_by_precision", [])
    lines = [
        r"\begin{tabular}{r" + "rrr" * len(rungs) + "}",
        r"\toprule",
        "decile & " + " & ".join(f"\\multicolumn{{3}}{{c}}{{{r}: mean $\\psig$ / event rate / cov.\\ 90}}" for r in rungs) + r" \\",
        r"\midrule",
    ]
    deciles = sorted({r["decile"] for r in t})
    for d in deciles:
        cells = [str(d)]
        for rg in rungs:
            m = [r for r in t if r["rung"] == rg and r["decile"] == d]
            if m:
                r = m[0]
                cells += [f3(r["mean_p_sig"]), f3(r["event_rate"]), f3(r["coverage_90"], 2)]
            else:
                cells += ["", "", ""]
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(out, f"calibration-{source}.tex", rep["_path"], "\n".join(lines) + "\n")


def decision_table(rep, source, out):
    t = rep["tables"]["decision_value"]
    keys = sorted({(r["policy"], r["rung"]) for r in t}, key=lambda k: (k[0] != "random", k[0] != "p_win", k[1]))
    lines = [r"\begin{tabular}{llrr}", r"\toprule", r"policy & model & captured fraction (mean over origins) & regret (mean) \\", r"\midrule"]
    for pol, rg in keys:
        rows = [r for r in t if r["policy"] == pol and r["rung"] == rg]
        cf = statistics.mean(r["captured_fraction"] for r in rows)
        rg_ = statistics.mean(r["regret"] for r in rows)
        lines.append(f"{esc(pol)} & {esc(rg)} & {f3(cf)} & {f3(rg_, 1)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(out, f"decision-{source}.tex", rep["_path"], "\n".join(lines) + "\n")


def abstention_table(rep, source, out):
    t = rep["tables"]["abstention"]
    lines = [r"\begin{tabular}{lrrrrrr}", r"\toprule", r"cell & n & rate & support & novelty & reliability & instability \\", r"\midrule"]
    for r in t:
        lines.append(
            f"{esc(r['cell'])} & {r['n']} & {f3(r['rate'])} & {r['support']} & {r['novelty']} & {r['reliability']} & {r['instability']} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(out, f"abstention-{source}.tex", rep["_path"], "\n".join(lines) + "\n")


def selection_table(rep, source, out):
    t = rep["tables"].get("p2_selection_by_cell", [])
    if not t:
        return
    lines = [
        r"\begin{tabular}{llrrrr}",
        r"\toprule",
        r"cell & selection & mean $\lambda$ & share $\lambda=0$ & mean bandwidth mult. & origins \\",
        r"\midrule",
    ]
    for r in t:
        lines.append(
            f"{esc(r['cell'])} & {esc(r['selection'])} & {f3(r['lambda_mean'], 2)} & "
            f"{f3(r['share_lambda_zero'], 2)} & {f3(r['bandwidth_mult_mean'], 2)} & {r['origins']} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(out, f"selection-{source}.tex", rep["_path"], "\n".join(lines) + "\n")


def gates_table(path, out):
    g = load(path)
    bt = g.get("by_target", {})
    lines = [r"\begin{tabular}{lrr}", r"\toprule", r"power target & rows for skill 0.20 & rows for skill 0.10 \\", r"\midrule"]
    for k in sorted(bt):
        v = bt[k]
        lines.append(f"{k} & {v.get('n_200', '')} & {v.get('n_400', '')} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(
        out,
        "gates.tex",
        f"{path} (base rate {g.get('base_rate')}, reps {g.get('reps')}, bootstrap {g.get('bootstrap')}, seed {g.get('seed')})",
        "\n".join(lines) + "\n",
    )


def ablation_table(reports_dir, source, out):
    files = sorted(glob.glob(os.path.join(reports_dir, "ablations", f"backtest-{source}-*.json")))
    lines = [r"\begin{tabular}{lrrr}", r"\toprule", r"setting & P2 log score & P2 CRPS & P2 Brier skill \\", r"\midrule"]
    for fpath in files:
        rep = load(fpath)
        setting = os.path.basename(fpath).split("--", 1)[-1].rsplit(".json", 1)[0]
        rows = [r for r in rep["tables"]["aggregate"] if r["cell"] == "ALL" and r["rung"] == "P2"]
        if rows:
            r = rows[0]
            lines.append(f"{esc(setting)} & {f3(r['logscore'])} & {f3(r['crps'], 2)} & {f3(r['brier_skill'])} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(out, f"ablations-{source}.tex", f"{reports_dir}/ablations/backtest-{source}-*.json ({len(files)} files)", "\n".join(lines) + "\n")


def learning_table(path, source, out):
    d = load(path)
    rows = d.get("rows", [])
    rungs = sorted({r["rung"] for r in rows})
    fracs = sorted({r["fraction"] for r in rows})
    lines = [
        r"\begin{tabular}{r" + "r" * len(rungs) + "}",
        r"\toprule",
        "fraction of ledger & " + " & ".join(f"{esc(r)} skill" for r in rungs) + r" \\",
        r"\midrule",
    ]
    for fr in fracs:
        cells = [f"{fr:.2f}"]
        for rg in rungs:
            m = [r for r in rows if r["rung"] == rg and r["fraction"] == fr]
            cells.append(interval(m[0], "skill") if m else "")
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    g = d.get("gates", {})
    write(
        out, f"learning-{source}.tex", f"{path} (held-out rows {d.get('heldout_rows')}, seeds {d.get('seeds')}, gates {g})", "\n".join(lines) + "\n"
    )


def cautionary_table(reports_dir, out):
    """By decile of REALIZED standard error on the naive-protocol run (relative lift, realized s_star)."""
    files = sorted(glob.glob(os.path.join(reports_dir, "ablations", "scores-upworthy-*effect-scale-relative*.parquet")))
    if not files:
        print("no cautionary scores parquet")
        return
    import pandas as pd

    s = pd.read_parquet(files[-1])
    rows = []
    for rung in ("P1", "P2"):
        d = s[s["rung"] == rung].copy()
        d["dec"] = pd.qcut(d["s"], 10, labels=False)
        g = d.groupby("dec")
        for dec, grp in g:
            rows.append(
                {
                    "rung": rung,
                    "decile": int(dec) + 1,
                    "s_med": float(grp["s"].median()),
                    "y_mean": float(grp["y"].mean()),
                    "event": float(grp["event"].mean()),
                    "p_sig": float(grp["p_sig"].mean()),
                    "cov90": float(((grp["y"] >= grp["lo90"]) & (grp["y"] <= grp["hi90"])).mean()),
                }
            )
    lines = [
        r"\begin{tabular}{rrrrrr}",
        r"\toprule",
        r"decile of realized $s$ & median $s$ & mean $y$ & event rate & P1 mean $\psig$ & P1 cov.\ 90 \\",
        r"\midrule",
    ]
    for r in [x for x in rows if x["rung"] == "P1"]:
        lines.append(f"{r['decile']} & {f3(r['s_med'], 1)} & {f3(r['y_mean'], 1)} & {f3(r['event'])} & {f3(r['p_sig'])} & {f3(r['cov90'], 2)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(out, "cautionary-upworthy.tex", files[-1], "\n".join(lines) + "\n")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--reports", required=True)
    ap.add_argument("--out", default="tables")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    for source in ("upworthy", "asos", "synthetic"):
        p = latest(os.path.join(a.reports, f"backtest-{source}-*.json"))
        if not p:
            print("no report for", source)
            continue
        rep = load(p)
        rep["_path"] = p
        main_table(rep, source, a.out)
        calibration_table(rep, source, a.out)
        decision_table(rep, source, a.out)
        abstention_table(rep, source, a.out)
        selection_table(rep, source, a.out)
        ablation_table(a.reports, source, a.out)
        lc = latest(os.path.join(a.reports, f"learning-curve-{source}-*.json"))
        if lc:
            learning_table(lc, source, a.out)
    gp = os.path.join(a.reports, "gates.json")
    if os.path.exists(gp):
        gates_table(gp, a.out)
    cautionary_table(a.reports, a.out)
