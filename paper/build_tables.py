"""Render the paper's LaTeX tables from Moot Court report JSON files.

Usage: python build_tables.py --reports "/Volumes/Crucial X10/mootcourt-data/reports" --out tables
Every table file starts with a comment naming the report file and snapshot id it came from, so each
number in the paper traces to one JSON path. No number is typed by hand.
"""

from __future__ import annotations

import argparse
import glob
import json
import os
import statistics


def f3(x, nd=3):
    return "" if x is None else f"{x:.{nd}f}"


def interval(r, key, nd=3):
    if r.get(key) is None:
        return ""
    return f"{f3(r[key], nd)} ({f3(r.get(key + '_lo'), nd)}, {f3(r.get(key + '_hi'), nd)})"


def challenger_rows(reports_dir, source):
    rows = []
    for fpath in sorted(glob.glob(os.path.join(reports_dir, "challengers", f"*{source}*.json"))):
        try:
            rep = load(fpath)
        except Exception:
            continue
        for r in rep.get("tables", {}).get("aggregate", []):
            if r.get("cell") == "ALL" and r.get("kind", "") not in ("ladder", "baseline"):
                r = dict(r)
                r["_file"] = os.path.basename(fpath)
                rows.append(r)
    return rows


def latest(pattern):
    files = sorted(glob.glob(pattern), key=os.path.getmtime)
    return files[-1] if files else None


def load(path):
    with open(path) as fh:
        return json.load(fh)


def esc(s):
    return str(s).replace("_", "\\_")


def write(out, name, header_comment, body):
    path = os.path.join(out, name)
    with open(path, "w") as fh:
        fh.write(f"% generated by paper/build_tables.py from {header_comment}\n")
        fh.write(body)
    print("wrote", path)


def main_table(rep, source, out):
    h, agg = rep["header"], rep["tables"]["aggregate"]
    rows = [r for r in agg if r["cell"] == "ALL"] + challenger_rows(os.path.dirname(rep["_path"]), source)
    lines = [
        r"\begin{tabular}{llrrrrrrrr}",
        r"\toprule",
        r"kind & model & tests & log score & CRPS & Brier skill (90\%) & dir.\ acc.\ / ceiling & cov.\ 80 / 90 & abst. & decid. \\",
        r"\midrule",
    ]
    for r in rows:
        dec = str(r.get("decidable_by_tests") or r.get("decidable") or "")
        dec = "yes" if dec.startswith("decidable at skill 0.20 and 0.10") else ("0.20 only" if "0.20 only" in dec else ("no" if dec else ""))
        lines.append(
            " & ".join(
                [
                    esc(r.get("kind", "rung")),
                    esc(r["rung"]),
                    str(r.get("n_tests", "")),
                    f3(r["logscore"]),
                    f3(r["crps"], 2),
                    interval(r, "brier_skill"),
                    f"{f3(r['direction_accuracy'])} / {f3(r.get('direction_ceiling'))}",
                    (f"{f3(r['coverage_80'], 2)} / {f3(r['coverage_90'], 2)}" if r.get("coverage_80") is not None else ""),
                    f3(r["abstention_rate"], 3),
                    dec,
                ]
            )
            + r" \\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    note = (
        f"source {source}, snapshot {h['snapshot_id']}, model {h['model_id']}, "
        f"{h['scored_rows']} scored rows over {h['origins_scored']} origins; "
        f"gate decision target {h.get('gate_decision_target')}"
    )
    write(out, f"main-{source}.tex", f"{rep['_path']} ({note})", "\n".join(lines) + "\n")


def calibration_table(rep, source, out, rungs=("P1", "P2")):
    t = rep["tables"].get("calibration_by_precision", [])
    lines = [
        r"\begin{tabular}{r" + "rrr" * len(rungs) + "}",
        r"\toprule",
        "decile & " + " & ".join(f"\\multicolumn{{3}}{{c}}{{{r}: mean $\\psig$ / event rate / cov.\\ 90}}" for r in rungs) + r" \\",
        r"\midrule",
    ]
    deciles = sorted({r["decile"] for r in t})
    for d in deciles:
        cells = [str(d)]
        for rg in rungs:
            m = [r for r in t if r["rung"] == rg and r["decile"] == d]
            if m:
                r = m[0]
                cells += [f3(r["mean_p_sig"]), f3(r["event_rate"]), f3(r["coverage_90"], 2)]
            else:
                cells += ["", "", ""]
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(out, f"calibration-{source}.tex", rep["_path"], "\n".join(lines) + "\n")


def decision_table(rep, source, out):
    """Captured fraction and regret per policy and model, as the mean over the per-origin rows of tables.decision_value.

    The pooled row (origin ALL) is a different quantity, the share over every chosen test, so it is left out of the means; the
    generated comment line says so and counts the origins averaged.
    """
    t = rep["tables"]["decision_value"]
    per_origin = [r for r in t if r["origin"] != "ALL"]
    if not per_origin:
        raise ValueError(f"{rep['_path']} has no per-origin decision value rows (only the pooled ALL row)")
    keys = sorted({(r["policy"], r["rung"]) for r in per_origin}, key=lambda k: (k[0] != "random", k[0] != "p_win", k[1]))
    lines = [r"\begin{tabular}{llrr}", r"\toprule", r"policy & model & captured fraction (mean over origins) & regret (mean) \\", r"\midrule"]
    for pol, rg in keys:
        rows = [r for r in per_origin if r["policy"] == pol and r["rung"] == rg]
        cf = statistics.mean(r["captured_fraction"] for r in rows)
        rg_ = statistics.mean(r["regret"] for r in rows)
        lines.append(f"{esc(pol)} & {esc(rg)} & {f3(cf)} & {f3(rg_, 1)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    n_origins = len({r["origin"] for r in per_origin})
    note = (f"{rep['_path']} (tables.decision_value; each mean is over the {n_origins} per-origin rows of the policy "
            "and excludes the pooled origin=ALL row)")
    write(out, f"decision-{source}.tex", note, "\n".join(lines) + "\n")


def abstention_table(rep, source, out):
    t = rep["tables"]["abstention"]
    lines = [r"\begin{tabular}{lrrrrrr}", r"\toprule", r"cell & n & rate & support & novelty & reliability & instability \\", r"\midrule"]
    for r in t:
        lines.append(
            f"{esc(r['cell'])} & {r['n']} & {f3(r['rate'])} & {r['support']} & {r['novelty']} & {r['reliability']} & {r['instability']} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(out, f"abstention-{source}.tex", rep["_path"], "\n".join(lines) + "\n")


def selection_table(rep, source, out):
    t = rep["tables"].get("p2_selection_by_cell", [])
    if not t:
        return
    lines = [
        r"\begin{tabular}{llrrrr}",
        r"\toprule",
        r"cell & selection & mean $\lambda$ & share $\lambda=0$ & mean bandwidth mult. & origins \\",
        r"\midrule",
    ]
    for r in t:
        lines.append(
            f"{esc(r['cell'])} & {esc(r['selection'])} & {f3(r['lambda_mean'], 2)} & "
            f"{f3(r['share_lambda_zero'], 2)} & {f3(r['bandwidth_mult_mean'], 2)} & {r['origins']} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(out, f"selection-{source}.tex", rep["_path"], "\n".join(lines) + "\n")


def gates_table(path, out):
    g = load(path)
    bt = g.get("by_target", {})
    lines = [r"\begin{tabular}{lrr}", r"\toprule", r"power target & rows for skill 0.20 & rows for skill 0.10 \\", r"\midrule"]
    for k in sorted(bt):
        v = bt[k]
        lines.append(f"{k} & {v.get('n_200', '')} & {v.get('n_400', '')} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(
        out,
        "gates.tex",
        f"{path} (base rate {g.get('base_rate')}, reps {g.get('reps')}, bootstrap {g.get('bootstrap')}, seed {g.get('seed')})",
        "\n".join(lines) + "\n",
    )


def ablation_table(reports_dir, source, out):
    files = [f for f in sorted(glob.glob(os.path.join(reports_dir, "ablations", f"backtest-{source}-*.json"))) if "--drop-trigger-" not in f]
    lines = [r"\begin{tabular}{lrrr}", r"\toprule", r"setting & P2 log score & P2 CRPS & P2 Brier skill \\", r"\midrule"]
    for fpath in files:
        rep = load(fpath)
        setting = os.path.basename(fpath).split("--", 1)[-1].rsplit(".json", 1)[0]
        rows = [r for r in rep["tables"]["aggregate"] if r["cell"] == "ALL" and r["rung"] == "P2"]
        if rows:
            r = rows[0]
            lines.append(f"{esc(setting)} & {f3(r['logscore'])} & {f3(r['crps'], 2)} & {f3(r['brier_skill'])} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(out, f"ablations-{source}.tex", f"{reports_dir}/ablations/backtest-{source}-*.json ({len(files)} files)", "\n".join(lines) + "\n")


def trigger_ablation_table(rep, reports_dir, source, out):
    """Skill on the cards that still issue, with one abstention trigger switched off at a time (the primary rung, all cells).

    Every trigger run must be on the main report's snapshot: a run from another snapshot would put rows of two ledgers in one table.
    When the runs carry ``tables.released_rows`` (the rows the full trigger set abstained on and the ablation issued), a second file
    ``trigger-released-<source>.tex`` prints their scores.
    """
    names = ("support", "novelty", "reliability", "instability")
    main_sid = rep["header"]["snapshot_id"]
    runs = [("none (main run)", rep, rep["_path"])]
    for name in names:
        hits = sorted(glob.glob(os.path.join(reports_dir, "ablations", f"backtest-{source}-*--drop-trigger-{name}.json")))
        if hits:
            doc = load(hits[-1])
            if doc["header"]["snapshot_id"] != main_sid:
                raise ValueError(
                    f"{hits[-1]} is a trigger run on snapshot {doc['header']['snapshot_id']}, "
                    f"but the main report {rep['_path']} is on snapshot {main_sid}"
                )
            runs.append((f"drop {name}", doc, hits[-1]))
    if len(runs) == 1:
        return
    lines = [
        r"\begin{tabular}{lrrrrr}",
        r"\toprule",
        r"setting & abst.\ rate & issued rows & log score, issued & Brier, issued & dir.\ acc., issued \\",
        r"\midrule",
    ]
    for label, doc, _path in runs:
        rows = [r for r in doc["tables"]["aggregate"] if r["cell"] == "ALL" and r["rung"] == "P2"]
        if not rows:
            continue
        r = rows[0]
        lines.append(
            f"{esc(label)} & {f3(r['abstention_rate'])} & {r.get('n_nonabstained', '')} & {interval(r, 'logscore_nonabstained')} & "
            f"{interval(r, 'brier_nonabstained')} & {interval(r, 'direction_accuracy_nonabstained')} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(out, f"trigger-ablation-{source}.tex", "; ".join(p for _l, _d, p in runs), "\n".join(lines) + "\n")
    released = [(label, doc, p) for label, doc, p in runs[1:] if doc["tables"].get("released_rows")]
    if released:
        rl = [
            r"\begin{tabular}{lrrrrr}",
            r"\toprule",
            r"setting & released rows & tests & log score (90\%) & Brier skill (90\%) & dir.\ acc.\ (90\%) \\",
            r"\midrule",
        ]
        for label, doc, _p in released:
            r = next((x for x in doc["tables"]["released_rows"] if x["cell"] == "ALL" and x["rung"] == "P2"), None)
            if r is None:
                continue
            rl.append(
                f"{esc(label)} & {r['n']} & {r['n_tests']} & {interval(r, 'logscore')} & {interval(r, 'brier_skill')} & "
                f"{interval(r, 'direction_accuracy')} \\\\"
            )
        rl += [r"\bottomrule", r"\end{tabular}"]
        write(
            out,
            f"trigger-released-{source}.tex",
            "; ".join(p for _l, _d, p in released)
            + " (tables.released_rows, rung P2, cell ALL: rows abstained in the main run and issued without the trigger)",
            "\n".join(rl) + "\n",
        )


def drift_table(rep, source, out, rungs=("P0", "P1", "P2")):
    """Scores by the calendar year in which the test started (tables.score_by_year), all cells pooled."""
    t = [r for r in rep["tables"].get("score_by_year", []) if r["cell"] == "ALL" and r["rung"] in rungs]
    if not t:
        return
    lines = [
        r"\begin{tabular}{rlrrrrrr}",
        r"\toprule",
        r"year & model & rows & tests & log score (90\%) & Brier skill (90\%) & dir.\ acc. & abst. \\",
        r"\midrule",
    ]
    for r in sorted(t, key=lambda x: (x["year"], rungs.index(x["rung"]))):
        lines.append(
            f"{r['year']} & {esc(r['rung'])} & {r['n']} & {r['n_tests']} & {interval(r, 'logscore')} & {interval(r, 'brier_skill')} & "
            f"{f3(r['direction_accuracy'])} & {f3(r['abstention_rate'])} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(out, f"drift-{source}.tex", f"{rep['_path']} (tables.score_by_year)", "\n".join(lines) + "\n")


def replay_table(path, source, out):
    """The weekly replay summed by calendar quarter of the week, with the typed misses and the weeks the loop would have flagged."""
    import pandas as pd

    d = load(path)
    w = pd.DataFrame(d["weeks"])
    w["quarter"] = pd.to_datetime(w["week_start"], utc=True).dt.tz_localize(None).dt.to_period("Q").astype(str)
    kinds = ["hit", "magnitude_miss", "direction_miss", "confident_but_wrong", "abstained_but_clear"]
    lines = [
        r"\begin{tabular}{lrrrrrrrrrrr}",
        r"\toprule",
        r"quarter & weeks & cards & joined & abst. & hit & magn. & dir. & conf.\ wrong & abst.\ clear & cov.\ 90 (last wk) & flagged wks \\",
        r"\midrule",
    ]
    for q, g in w.groupby("quarter", sort=True):
        cards, ab = int(g["cards_issued"].sum()), int(g["abstained"].sum())
        counts = [int(sum(m[k] for m in g["miss_counts"])) for k in kinds]
        last_cov = next((c for c in reversed(g["coverage_90"].tolist()) if c is not None and c == c), None)
        lines.append(
            f"{q} & {len(g)} & {cards} & {int(g['outcomes_joined'].sum())} & {f3(ab / cards if cards else None, 2)} & "
            + " & ".join(str(c) for c in counts)
            + f" & {f3(last_cov, 2)} & {int(g['flagged'].sum())} \\\\"
        )
    t = d["totals"]
    lines += [
        r"\midrule",
        f"all & {d['header']['n_weeks']} & {t['cards_issued']} & {t['outcomes_joined']} & "
        f"{f3(t['abstained'] / t['cards_issued'] if t['cards_issued'] else None, 2)} & "
        + " & ".join(str(t["miss_counts"][k]) for k in kinds)
        + f" & {f3(t.get('coverage_90_all'), 2)} & {t['n_flagged_weeks']} \\\\",
        r"\bottomrule",
        r"\end{tabular}",
    ]
    write(out, f"replay-{source}.tex", path, "\n".join(lines) + "\n")


def learning_table(path, source, out):
    d = load(path)
    rows = d.get("rows", [])
    rungs = sorted({r["rung"] for r in rows})
    fracs = sorted({r["fraction"] for r in rows})
    lines = [
        r"\begin{tabular}{r" + "r" * len(rungs) + "}",
        r"\toprule",
        "fraction of ledger & " + " & ".join(f"{esc(r)} skill" for r in rungs) + r" \\",
        r"\midrule",
    ]
    for fr in fracs:
        cells = [f"{fr:.2f}"]
        for rg in rungs:
            m = [r for r in rows if r["rung"] == rg and r["fraction"] == fr]
            cells.append(interval(m[0], "skill") if m else "")
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    g = d.get("gates", {})
    write(
        out, f"learning-{source}.tex", f"{path} (held-out rows {d.get('heldout_rows')}, seeds {d.get('seeds')}, gates {g})", "\n".join(lines) + "\n"
    )


def cautionary_table(reports_dir, out):
    """By decile of REALIZED standard error on the naive-protocol run (relative lift, realized s_star)."""
    files = sorted(glob.glob(os.path.join(reports_dir, "ablations", "scores-upworthy-*effect-scale-relative*.parquet")))
    if not files:
        print("no cautionary scores parquet")
        return
    import pandas as pd

    s = pd.read_parquet(files[-1])
    rows = []
    for rung in ("P1", "P2"):
        d = s[s["rung"] == rung].copy()
        d["dec"] = pd.qcut(d["s"], 10, labels=False)
        g = d.groupby("dec")
        for dec, grp in g:
            rows.append(
                {
                    "rung": rung,
                    "decile": int(dec) + 1,
                    "s_med": float(grp["s"].median()),
                    "y_mean": float(grp["y"].mean()),
                    "event": float(grp["event"].mean()),
                    "p_sig": float(grp["p_sig"].mean()),
                    "cov90": float(((grp["y"] >= grp["lo90"]) & (grp["y"] <= grp["hi90"])).mean()),
                }
            )
    lines = [
        r"\begin{tabular}{rrrrrr}",
        r"\toprule",
        r"decile of realized $s$ & median $s$ & mean $y$ & event rate & P1 mean $\psig$ & P1 cov.\ 90 \\",
        r"\midrule",
    ]
    for r in [x for x in rows if x["rung"] == "P1"]:
        lines.append(f"{r['decile']} & {f3(r['s_med'], 1)} & {f3(r['y_mean'], 1)} & {f3(r['event'])} & {f3(r['p_sig'])} & {f3(r['cov90'], 2)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(out, "cautionary-upworthy.tex", files[-1], "\n".join(lines) + "\n")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--reports", required=True)
    ap.add_argument("--out", default="tables")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    for source in ("upworthy", "asos", "synthetic"):
        p = latest(os.path.join(a.reports, f"backtest-{source}-*.json"))
        if not p:
            print("no report for", source)
            continue
        rep = load(p)
        rep["_path"] = p
        main_table(rep, source, a.out)
        calibration_table(rep, source, a.out)
        decision_table(rep, source, a.out)
        abstention_table(rep, source, a.out)
        selection_table(rep, source, a.out)
        ablation_table(a.reports, source, a.out)
        trigger_ablation_table(rep, a.reports, source, a.out)
        drift_table(rep, source, a.out)
        rp = latest(os.path.join(a.reports, f"replay-{source}-*.json"))
        if rp:
            replay_table(rp, source, a.out)
        lc = latest(os.path.join(a.reports, f"learning-curve-{source}-*.json"))
        if lc:
            learning_table(lc, source, a.out)
    gp = os.path.join(a.reports, "gates.json")
    if os.path.exists(gp):
        gates_table(gp, a.out)
    cautionary_table(a.reports, a.out)
