"""Render the paper's LaTeX tables from Moot Court report JSON files.

Usage: python build_tables.py --reports "/Volumes/Crucial X10/mootcourt-data/reports" --out tables
Every table file starts with a comment naming the report file and snapshot id it came from, so each
number in the paper traces to one JSON path. No number is typed by hand. The summary tables of the body and the appendix are specified in
paper/summary_tables/ and written from here as well.
"""

from __future__ import annotations

import argparse
import glob
import json
import os
import statistics


def f3(x, nd=3):
    """``x`` to ``nd`` places; a value that rounds to zero prints as an unsigned zero, so no table holds "-0.0000"."""
    if x is None:
        return ""
    text = f"{x:.{nd}f}"
    return text[1:] if text.startswith("-") and float(text) == 0.0 else text


def fr(x):
    """Regret in the units of y: one decimal when large (Upworthy), three when small (ASOS), never a printed 0.0 for a nonzero value."""
    return "" if x is None else (f"{x:.1f}" if abs(x) >= 10 else f3(x, 3))


def interval(r, key, nd=3):
    if r.get(key) is None:
        return ""
    return f"{f3(r[key], nd)} ({f3(r.get(key + '_lo'), nd)}, {f3(r.get(key + '_hi'), nd)})"


def challenger_rows(reports_dir, source):
    rows = []
    for fpath in sorted(glob.glob(os.path.join(reports_dir, "challengers", f"*{source}*.json"))):
        try:
            rep = load(fpath)
        except Exception:
            continue
        for r in rep.get("tables", {}).get("aggregate", []):
            if r.get("cell") == "ALL" and r.get("kind", "") not in ("ladder", "baseline"):
                r = dict(r)
                r["_file"] = os.path.basename(fpath)
                rows.append(r)
    return rows


def latest(pattern):
    files = sorted(glob.glob(pattern), key=os.path.getmtime)
    return files[-1] if files else None


def load(path):
    with open(path) as fh:
        return json.load(fh)


def esc(s):
    return str(s).replace("_", "\\_")


REPORTS_ROOT = None   # the run folder the tables are built from; header paths are written relative to it (round 01, R4; call 240)


def set_reports_root(root):
    """Remember the run folder so that every header comment names its sources relative to it and never by an absolute path."""
    global REPORTS_ROOT
    REPORTS_ROOT = None if root is None else str(root)


def relative_to_run(text, root):
    """``text`` with every spelling of the run folder ``root`` (as given, normalized, absolute, real) and its separator removed."""
    if not root:
        return text
    forms = {str(root), os.path.normpath(root), os.path.abspath(root), os.path.realpath(root), os.path.expanduser(root)}
    for form in sorted(forms, key=len, reverse=True):
        form = form.rstrip(os.sep)
        if form:
            text = text.replace(form + os.sep, "").replace(form + "/", "")
    return text


def write(out, name, header_comment, body):
    path = os.path.join(out, name)
    with open(path, "w") as fh:
        fh.write(f"% generated by paper/build_tables.py from {relative_to_run(header_comment, REPORTS_ROOT)}\n")
        fh.write(body)
    print("wrote", path)


def main_table(rep, source, out):
    h, agg = rep["header"], rep["tables"]["aggregate"]
    rows = [r for r in agg if r["cell"] == "ALL"]
    have = {r["rung"] for r in rows}
    # a run before the challengers joined the main report
    rows += [r for r in challenger_rows(os.path.dirname(rep["_path"]), source) if r["rung"] not in have]
    lines = [
        r"\begin{tabular}{llrrrrrrrrrr}",
        r"\toprule",
        r"kind & model & tests & log score & minus P1 (90\%) & CRPS & Brier / base / floor & Brier skill (90\%) & dir.\ acc.\ / ceiling & "
        r"cov.\ 80 / 90 & abst. & decid. \\",
        r"\midrule",
    ]
    for r in rows:
        dec = str(r.get("decidable_by_tests") or r.get("decidable") or "")
        dec = "yes" if dec.startswith("decidable at skill 0.20 and 0.10") else ("0.20 only" if "0.20 only" in dec else ("no" if dec else ""))
        lines.append(
            " & ".join(
                [
                    esc(r.get("kind", "rung")),
                    esc(r["rung"]),
                    str(r.get("n_tests", "")),
                    f3(r["logscore"]),
                    (interval(r, "logscore_vs_p1", 4) if r.get("logscore_vs_p1") is not None else ""),
                    f3(r["crps"], 2),
                    f"{f3(r.get('brier'), 4)} / {f3(r.get('brier_base'), 4)} / {f3(r.get('brier_floor'), 4)}" if r.get("brier") is not None else "",
                    interval(r, "brier_skill", 4),
                    f"{f3(r['direction_accuracy'])} / {f3(r.get('direction_ceiling'))}",
                    (f"{f3(r['coverage_80'], 2)} / {f3(r['coverage_90'], 2)}" if r.get("coverage_80") is not None else ""),
                    f3(r["abstention_rate"], 3),
                    dec,
                ]
            )
            + r" \\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    note = (
        f"source {source}, snapshot {h['snapshot_id']}, model {h['model_id']}, "
        f"{h['scored_rows']} scored rows over {h['origins_scored']} origins; "
        f"gate decision target {h.get('gate_decision_target')}"
    )
    write(out, f"main-{source}.tex", f"{rep['_path']} ({note})", "\n".join(lines) + "\n")


def calibration_table(rep, source, out, rungs=("P1", "P2")):
    t = rep["tables"].get("calibration_by_precision", [])
    lines = [
        r"\begin{tabular}{r" + "rrr" * len(rungs) + "}",
        r"\toprule",
        "decile & " + " & ".join(f"\\multicolumn{{3}}{{c}}{{{r}: mean $\\psig$ / event rate / cov.\\ 90}}" for r in rungs) + r" \\",
        r"\midrule",
    ]
    deciles = sorted({r["decile"] for r in t})
    for d in deciles:
        cells = [str(d)]
        for rg in rungs:
            m = [r for r in t if r["rung"] == rg and r["decile"] == d]
            if m:
                r = m[0]
                cells += [f3(r["mean_p_sig"]), f3(r["event_rate"]), f3(r["coverage_90"], 2)]
            else:
                cells += ["", "", ""]
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(out, f"calibration-{source}.tex", rep["_path"], "\n".join(lines) + "\n")


def _ranking_paired(rep, source):
    """The paired captured-lift differences of the run's extras file, for the headline archive's decision table; None when the run has no such key."""
    if source != "upworthy":
        return None
    extras = latest(os.path.join(os.path.dirname(rep["_path"]), f"paper-extras-{source}-*.json"))
    return load(extras).get("ranking_paired") if extras else None


def decision_table(rep, source, out):
    """Captured fraction and regret per policy and model, as the mean over the per-origin rows of tables.decision_value (25 percent budget).

    The pooled row (origin ALL) is a different quantity, the share over every chosen test, so it is left out of the means; the
    generated comment line says so and counts the origins averaged. A table with only the pooled row is refused. The pooled rows with their
    bootstrap intervals are in ``decision-intervals-<source>.tex`` (``decision_intervals_table``).
    """
    t = rep["tables"]["decision_value"]
    per_origin = [r for r in t if r["origin"] != "ALL" and r.get("budget", 0.25) == 0.25]
    if not per_origin:
        raise ValueError(f"{rep['_path']} has no per-origin decision value rows (only the pooled ALL row)")
    keys = sorted({(r["policy"], r["rung"]) for r in per_origin}, key=lambda k: (k[0] != "random", k[0] != "p_win", k[0], k[1]))
    lines = [r"\begin{tabular}{llrr}", r"\toprule", r"policy & model & captured fraction (mean over origins) & regret (mean) \\", r"\midrule"]
    for pol, rg in keys:
        rows = [r for r in per_origin if r["policy"] == pol and r["rung"] == rg]
        cf = statistics.mean(r["captured_fraction"] for r in rows)
        rg_ = statistics.mean(r["regret"] for r in rows)
        lines.append(f"{esc(pol)} & {esc(rg)} & {f3(cf)} & {fr(rg_)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    n_origins = len({r["origin"] for r in per_origin})
    note = (
        f"{rep['_path']} (tables.decision_value; each mean is over the {n_origins} per-origin rows of the policy "
        "and excludes the pooled origin=ALL row)"
    )
    write(out, f"decision-{source}.tex", note, "\n".join(lines) + "\n")
    decision_intervals_table(rep, source, out, paired=_ranking_paired(rep, source))


def decision_intervals_table(rep, source, out, paired=None):
    """The pooled decision value with its intervals, at every budget (tables.decision_value, origin ALL).

    Columns: captured_fraction with captured_fraction_lo and captured_fraction_hi, diff_matched (the captured fraction minus the arm-count-matched
    random policy's, the baseline H5 reads) with its interval and Bonferroni-adjusted bounds, regret with regret_lo and regret_hi, and
    constant_within_cell. The difference from plain random order stays in the JSON (diff_random) and is the captured fraction minus the random
    policy's row of the same table (round 02, R5: the matched columns are the ones read, and the table had ten columns).
    Every interval is a 90 percent bootstrap
    that resamples whole tests within each origin; random order is exact (K over n); a rung whose p_win is constant within a cell chooses by
    cell and then at random. ``paired`` is the extras key ``ranking_paired`` when a run has it: a row of P2 minus P1, paired by test,
    follows each budget's rungs, its difference in the captured column and its Bonferroni-adjusted bounds (over the two listed comparisons)
    in the adjusted column.
    """
    pooled = [r for r in rep["tables"]["decision_value"] if r["origin"] == "ALL"]
    if not pooled or "captured_fraction_lo" not in pooled[0]:
        return
    budgets = sorted({r.get("budget", 0.25) for r in pooled}, key=lambda b: (b != 0.25, b))
    lines = [
        r"\begin{tabular}{llrrrrrr}",
        r"\toprule",
        r"budget & policy & model & captured fraction (90\%) "
        r"& minus arm-count-matched random (90\%) & minus matched, Bonferroni-adjusted ($m$) & regret (90\%) & const.\ in cell \\",
        r"\midrule",
    ]
    for bud in budgets:
        rows = [r for r in pooled if r.get("budget", 0.25) == bud]
        keys = sorted({(r["policy"], r["rung"]) for r in rows}, key=lambda k: (k[0] != "random", k[0] != "p_win", k[0], k[1]))
        for pol, rg in keys:
            r = next(x for x in rows if x["policy"] == pol and x["rung"] == rg)
            cf = f"{f3(r['captured_fraction'])} ({f3(r.get('captured_fraction_lo'))}, {f3(r.get('captured_fraction_hi'))})"
            mt, madj = "", ""
            if r.get("diff_matched") is not None:
                mt = f"{f3(r['diff_matched'])} ({f3(r.get('diff_matched_lo'))}, {f3(r.get('diff_matched_hi'))})"
                madj = f"({f3(r['diff_matched_adjusted_lo'])}, {f3(r['diff_matched_adjusted_hi'])}) $m={r['family_size']}$"
            rgt = fr(r["regret"])
            if r.get("regret_lo") is not None:
                rgt += f" ({fr(r.get('regret_lo'))}, {fr(r.get('regret_hi'))})"
            const = "" if r.get("constant_within_cell") is None else ("yes" if r["constant_within_cell"] else "no")
            lines.append(f"{bud:g} & {esc(pol)} & {esc(rg)} & {cf} & {mt} & {madj} & {rgt} & {const} \\\\")
        if paired:
            d = paired["budgets"][f"{bud:.2f}"]["differences"]["P2_minus_P1"]
            lines.append(f"{bud:g} & paired by test & P2 minus P1 & {f3(d['estimate'])} ({f3(d['lo'])}, {f3(d['hi'])}) &  & "
                         f"({f3(d['adjusted_lo'])}, {f3(d['adjusted_hi'])}) $m={d['family_size']}$ &  &  \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    source_note = "; the paired row from the paper extras' ranking_paired" if paired else ""
    note = (
        f"{rep['_path']} (tables.decision_value, origin ALL{source_note}; intervals are 90 percent bootstrap by test within each origin; "
        "random order is "
        "exact, K over n; constant_within_cell: p_win is one number per cell, so the policy chooses by cell and then at random; the adjusted "
        "bounds are Bonferroni bounds for the m rungs compared with random order at the budget, docs/method.md calls 200 and 201; "
        "arm_count ranks by the "
        "number of contrasts, random_matched is random order within arm-count strata)"
    )
    write(out, f"decision-intervals-{source}.tex", note, "\n".join(lines) + "\n")


def coverage_ratio_table(rep, source, out, rungs=("P0", "P1", "P2")):
    """Coverage of the 90 percent interval within deciles of the realized over the planned standard error (tables.coverage_by_se_ratio)."""
    t = rep["tables"].get("coverage_by_se_ratio", [])
    if not t:
        return
    lines = [
        r"\begin{tabular}{r" + "r" * (2 + len(rungs)) + "}",
        r"\toprule",
        r"decile & ratio range & event rate (" + esc(rungs[0]) + ") & " + " & ".join(f"{esc(r)} cov.\\ 90" for r in rungs) + r" \\",
        r"\midrule",
    ]
    first = [r for r in t if r["rung"] == rungs[0]] or [r for r in t if r["rung"] == t[0]["rung"]]
    for row in first:
        cells = [str(row["decile"]), f"{f3(row['ratio_lo'], 2)} to {f3(row['ratio_hi'], 2)}", f3(row["event_rate"])]
        for rg in rungs:
            m = [r for r in t if r["rung"] == rg and r["decile"] == row["decile"]]
            cells.append(f3(m[0]["coverage_90"], 2) if m else "")
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(
        out,
        f"coverage-ratio-{source}.tex",
        f"{rep['_path']} (tables.coverage_by_se_ratio, deciles of the realized over the planned standard error)",
        "\n".join(lines) + "\n",
    )


def ece_table(rep, source, out, rungs=("P0", "P1", "P2")):
    """ECE with the clustered null percentile, the independent percentile, the design effect and the adjusted skill bounds (cell ALL)."""
    rows = [r for r in rep["tables"]["aggregate"] if r["cell"] == "ALL" and r["rung"] in rungs]
    if not rows:
        return
    lines = [
        r"\begin{tabular}{lrrrrrrr}",
        r"\toprule",
        r"model & ECE & pct.\ (clustered null) & pct.\ (independent) & design effect & Brier skill (90\%) & adjusted bounds ($m$) \\",
        r"\midrule",
    ]
    for r in sorted(rows, key=lambda x: rungs.index(x["rung"])):
        adj = f"({f3(r.get('adjusted_lo'))}, {f3(r.get('adjusted_hi'))}) $m={r.get('family_size')}$" if r.get("adjusted_lo") is not None else ""
        lines.append(
            f"{esc(r['rung'])} & {f3(r.get('ece'), 4)} & {f3(r.get('ece_percentile'), 1)} & {f3(r.get('ece_percentile_independent'), 1)} & "
            f"{f3(r.get('design_effect'), 2)} & {interval(r, 'brier_skill', 4)} & {adj} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(
        out,
        f"ece-{source}.tex",
        f"{rep['_path']} (tables.aggregate, cell ALL; the null draws contrasts of one test together, 500 draws, so 100 means above every draw)",
        "\n".join(lines) + "\n",
    )


